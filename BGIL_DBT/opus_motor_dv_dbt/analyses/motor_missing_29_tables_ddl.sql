-- DDL for the 29 OPUS Motor source tables missing from BAGIC_PROD_MIRROR_DB.OPUS_GG_DWHSTAGE,
-- created in BAGIC_PREPROD_CURATED_DB.UTILS (source motor_test_raw), where the ingestion team loads them.
-- The other 64 motor tables are year-to-date copies made by motor_test_raw_ytd_copy.sql, which skips these 29.
-- Generated from validation/Motor_tables_details.xlsx (Oracle source DDL: table, column, data type).
-- Plain SQL: run in a Snowflake worksheet. 'create table if not exists' never replaces an existing table.
--
-- Oracle -> Snowflake types (the sheet has no lengths or precisions):
--   VARCHAR2, NVARCHAR2, CHAR, CLOB -> VARCHAR        (no length: the Snowflake maximum)
--   NUMBER                          -> NUMBER(38,10)  (keeps decimals; Snowflake's plain NUMBER is (38,0))
--   DATE                            -> TIMESTAMP_NTZ  (an Oracle DATE carries a time of day)
--   TIMESTAMP(6)                    -> TIMESTAMP_NTZ(6)
--   ROWID                           -> VARCHAR(18)
-- Added last on every table: INC_JOB_UPDATED_AT TIMESTAMP_NTZ, the load time the ingestion job must
-- populate (every stg1 model reads it; it is not in the Oracle DDL).
-- BJAZ_MOT_GEN_RATE_MASTER and BJAZ_MOT_WAR_PLANS_EXTN appear twice in the sheet with identical
-- columns and types; each column is created once.

-- 0) Optional, before running: how the 64 motor tables already in OPUS_GG_DWHSTAGE type their columns.
--    If NUMBER columns there are not NUMBER(38,10), change the NUMBER(38,10) below to match.
select data_type, numeric_precision, numeric_scale, count(*) as columns
from BAGIC_PROD_MIRROR_DB.INFORMATION_SCHEMA.COLUMNS
where table_schema = 'OPUS_GG_DWHSTAGE'
  and table_name in ('BA_QUOTE_MOT_DTLS', 'BJAZ_CLM_BASE_MOT_EXT', 'BJAZ_MOT_ONLINE_POL_DTLS')
group by 1, 2, 3
order by columns desc;

