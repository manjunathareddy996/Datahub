     where run_id = $DM_H_RUN and phase = 'BEFORE' and satellite = 'SAT_RISK_PERSON_TRAVEL'
),
a as (
    select * from BAGIC_PREPROD_CURATED_DB.UTILS.DM_H_CDC_SNAPSHOT
     where run_id = $DM_H_RUN and phase = 'AFTER'  and satellite = 'SAT_RISK_PERSON_TRAVEL'
),
k as (
    select b.satellite, b.record_source, b.hkey, b.cdk,
           not equal_null(b.raw_hash, a.raw_hash) as raw_changed,
           a.sat_rows - b.sat_rows as new_rows
