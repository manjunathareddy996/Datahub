-- 3. OPUS — [automate_dv.sat] SAT_COVERAGE_CONDITIONS   [Implemented]
-- HASHDIFF column HASHDIFF. Recomputed exactly as automate_dv 0.11.5 / sat_multi_source
-- computes it, from the payload stored on the same row. A match proves every payload
-- change changes the HASHDIFF, which is what drives a new row. standard satellite,
-- automate_dv.sat; PK COVERAGE_HKEY; 1 RECORD_SOURCE group(s): OPUS_TRAVEL_BJAZ_TRV_PLAN
-- [2 col(s)].
----------------------------------------------------------------------------------------
-- STEP 1 (static, run anytime) -- HASHDIFF integrity. PASS here = the change-detection fingerprint is sound. SQL query (a) -- HASHDIFF integrity (all rows of this project)
select 'OPUS' as project, 'SAT_COVERAGE_CONDITIONS' as satellite, 'OPUS_TRAVEL_BJAZ_TRV_PLAN' as scope,
       count(*) as rows_checked,
       count_if(HASHDIFF is null) as null_hashdiff,
       count_if(HASHDIFF <> CAST(MD5_BINARY(CONCAT_WS('||', IFNULL(NULLIF(UPPER(TRIM(CAST(CONDITION_DESCRIPTION AS VARCHAR))), ''), '^^'), IFNULL(NULLIF(UPPER(TRIM(CAST(WAITING_PERIOD_CONDITION AS VARCHAR))), ''), '^^'))) AS BINARY(16))) as hashdiff_mismatch,
       array_slice(array_agg(iff(HASHDIFF <> CAST(MD5_BINARY(CONCAT_WS('||', IFNULL(NULLIF(UPPER(TRIM(CAST(CONDITION_DESCRIPTION AS VARCHAR))), ''), '^^'), IFNULL(NULLIF(UPPER(TRIM(CAST(WAITING_PERIOD_CONDITION AS VARCHAR))), ''), '^^'))) AS BINARY(16)), to_varchar(COVERAGE_HKEY, 'HEX'), null)) within group (order by COVERAGE_HKEY), 0, 3) as mismatch_examples,
       iff(null_hashdiff = 0 and hashdiff_mismatch = 0, 'PASS', 'FAIL') as status
  from BAGIC_PREPROD_CURATED_DB.BGIL_DATA_MODEL.SAT_COVERAGE_CONDITIONS
 where (RECORD_SOURCE = 'OPUS_TRAVEL_BJAZ_TRV_PLAN');

-- STEP 2 (BEFORE) -- set $DM_H_RUN (with your <M#>) and $DM_H_PHASE='BEFORE', then run this CDC capture. Re-run it again in STEP 6 after setting phase to AFTER.
insert into BAGIC_PREPROD_CURATED_DB.UTILS.DM_H_CDC_SNAPSHOT (run_id, phase, project, satellite, record_source, hkey, cdk, sat_rows, sat_max_ldts, raw_hash, captured_at)
with s1 as (  -- BEFORE: first 100 keys by hash; AFTER: exactly the keys captured BEFORE
    select hkey from (
        select distinct COVERAGE_HKEY as hkey from BAGIC_PREPROD_CURATED_DB.BGIL_DATA_MODEL.SAT_COVERAGE_CONDITIONS where RECORD_SOURCE = 'OPUS_TRAVEL_BJAZ_TRV_PLAN' order by hkey limit 100
    ) where $DM_H_PHASE = 'BEFORE'
    union
    select distinct hkey from BAGIC_PREPROD_CURATED_DB.UTILS.DM_H_CDC_SNAPSHOT
     where $DM_H_PHASE = 'AFTER' and run_id = $DM_H_RUN and phase = 'BEFORE'
       and satellite = 'SAT_COVERAGE_CONDITIONS' and record_source = 'OPUS_TRAVEL_BJAZ_TRV_PLAN'
),
e1 as (  -- expected value(s) at the latest RAW load timestamp per key
    select *
      from (
        -- via stg_travel__bjaz_trv_plan
        select MD5_BINARY(NULLIF(UPPER(TRIM(CAST('HUB_COVERAGE|' || ((nullif(trim(to_varchar("COVER_CODE")), ''))) AS VARCHAR))), '')) as hkey,
               ("INC_JOB_UPDATED_AT"::timestamp_ntz) as ldts,
               to_varchar((nullif(trim(to_varchar("CLAIM_COVER_DESC")), ''))) as CONDITION_DESCRIPTION,
               to_varchar((nullif(trim(to_varchar("DEDUCTABLE_TIME")), ''))) as WAITING_PERIOD_CONDITION
          from BAGIC_PREPROD_CURATED_DB.UTILS.BJAZ_TRV_PLAN
      )
     where hkey in (select hkey from s1) and ldts is not null
    qualify rank() over (partition by hkey order by ldts desc) = 1
),
n1 as (  -- satellite history per sampled key
    select COVERAGE_HKEY as hkey, '' as cdk, count(*) as sat_rows, max(LOAD_DATETIME) as sat_max_ldts
      from BAGIC_PREPROD_CURATED_DB.BGIL_DATA_MODEL.SAT_COVERAGE_CONDITIONS
     where RECORD_SOURCE = 'OPUS_TRAVEL_BJAZ_TRV_PLAN' and COVERAGE_HKEY in (select hkey from s1)
     group by 1, 2
),
x1 as (  -- normalised RAW payload hash (UPPER / TRIM / '^^' like the HASHDIFF)
    select e.hkey, '' as cdk, min(md5(concat_ws('||', IFNULL(NULLIF(UPPER(TRIM(CAST(e.CONDITION_DESCRIPTION AS VARCHAR))), ''), '^^'), IFNULL(NULLIF(UPPER(TRIM(CAST(e.WAITING_PERIOD_CONDITION AS VARCHAR))), ''), '^^')))) as raw_hash
      from e1 e group by 1, 2
)
select $DM_H_RUN, $DM_H_PHASE, 'OPUS', 'SAT_COVERAGE_CONDITIONS', 'OPUS_TRAVEL_BJAZ_TRV_PLAN',
       coalesce(n.hkey, x.hkey), coalesce(n.cdk, x.cdk), coalesce(n.sat_rows, 0), n.sat_max_ldts, x.raw_hash, current_timestamp()
  from n1 n full outer join x1 x on x.hkey = n.hkey and x.cdk = n.cdk;

-- STEP 3 (pick a key) -- map a sampled BEFORE hkey to its RAW business key. Copy one business_key value to use in STEP 4.
with s_bk as (  -- sampled BEFORE hkeys for this satellite
    select distinct hkey from BAGIC_PREPROD_CURATED_DB.UTILS.DM_H_CDC_SNAPSHOT
     where run_id = $DM_H_RUN and phase = 'BEFORE' and satellite = 'SAT_COVERAGE_CONDITIONS'
)
-- via stg_travel__bjaz_trv_plan (BAGIC_PREPROD_CURATED_DB.UTILS.BJAZ_TRV_PLAN)
select 'SAT_COVERAGE_CONDITIONS' as satellite, 'OPUS_TRAVEL_BJAZ_TRV_PLAN' as record_source,
       MD5_BINARY(NULLIF(UPPER(TRIM(CAST('HUB_COVERAGE|' || ((nullif(trim(to_varchar("COVER_CODE")), ''))) AS VARCHAR))), '')) as hkey, coalesce(to_varchar("COVER_CODE"), '^^') as business_key, ("INC_JOB_UPDATED_AT"::timestamp_ntz) as inc_job_updated_at,
       'BAGIC_PREPROD_CURATED_DB.UTILS.BJAZ_TRV_PLAN' as raw_table
  from BAGIC_PREPROD_CURATED_DB.UTILS.BJAZ_TRV_PLAN
 where MD5_BINARY(NULLIF(UPPER(TRIM(CAST('HUB_COVERAGE|' || ((nullif(trim(to_varchar("COVER_CODE")), ''))) AS VARCHAR))), '')) in (select hkey from s_bk)
limit 20;

-- STEP 4 (force the change) -- fill <BK> from STEP 3, run this UPDATE in UTILS. STEP 5: dbt run --select this sat. STEP 6: set phase='AFTER' and re-run STEP 2.
-- OPUS_TRAVEL_BJAZ_TRV_PLAN (BAGIC_PREPROD_CURATED_DB.UTILS.BJAZ_TRV_PLAN): change ONE sampled key (fill <..> from the b-map result)
update BAGIC_PREPROD_CURATED_DB.UTILS.BJAZ_TRV_PLAN
   set "CLAIM_COVER_DESC" = coalesce(to_varchar("CLAIM_COVER_DESC"), '') || '_T',
       "INC_JOB_UPDATED_AT" = current_timestamp()
 where "COVER_CODE" = '<COVER_CODE>';

-- STEP 7 (result for THIS sat) -- after AFTER capture, run this. PASS = every changed key got >= 1 new row; NOT TESTED = no change reached the sample.
with b as (
    select * from BAGIC_PREPROD_CURATED_DB.UTILS.DM_H_CDC_SNAPSHOT
     where run_id = $DM_H_RUN and phase = 'BEFORE' and satellite = 'SAT_COVERAGE_CONDITIONS'
),
a as (
    select * from BAGIC_PREPROD_CURATED_DB.UTILS.DM_H_CDC_SNAPSHOT
     where run_id = $DM_H_RUN and phase = 'AFTER'  and satellite = 'SAT_COVERAGE_CONDITIONS'
),
k as (
    select b.satellite, b.record_source, b.hkey, b.cdk,
           not equal_null(b.raw_hash, a.raw_hash) as raw_changed,
           a.sat_rows - b.sat_rows as new_rows
      from b join a
        on a.satellite = b.satellite and a.record_source = b.record_source
       and a.hkey = b.hkey and equal_null(a.cdk, b.cdk)
)
select 'OPUS' as project, satellite, record_source,
       count(*) as changed_keys,
       count_if(new_rows >= 1) as changed_with_new_row,
       count_if(new_rows < 1)  as changed_without_new_row,
       iff(changed_keys = 0, 'NOT TESTED (no source change in sample)',
           iff(changed_without_new_row = 0, 'PASS', 'FAIL')) as status
  from k
 where raw_changed
 group by satellite, record_source
 order by iff(status = 'FAIL', 0, 1), record_source;



