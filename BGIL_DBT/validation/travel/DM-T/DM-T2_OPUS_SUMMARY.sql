       count(*) as sections,
       count_if("RESULT" = 'Pass') as pass,
       count_if("RESULT" = 'Fail') as fail,
       count_if("ROWS_IN_SCOPE" = 0) as zero_row_sections
  from table(result_scan(last_query_id()))
 group by rollup ("MEMBER")
 order by "MEMBER" nulls last;
