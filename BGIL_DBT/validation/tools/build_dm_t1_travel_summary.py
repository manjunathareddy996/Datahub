#!/usr/bin/env python3
"""
Build one runnable summary query per project for travel DM-T1 (load metadata
populated) from the generated per-section files, same layout as the DM-T2
summaries:

    travel/DM-T/DM-T1_OPUS.sql     -> travel/DM-T/DM-T1_OPUS_SUMMARY.sql
    travel/DM-T/DM-T1_MAXIMUS.sql  -> travel/DM-T/DM-T1_MAXIMUS_SUMMARY.sql

Each output holds three statements, run top to bottom:
  1. Preflight -- tables / columns the sections read that are missing in
                  BGIL_DATA_MODEL (any row = statement 2 would not compile).
  2. Main      -- one row per section (section_no / member / result /
                  failing_rows / remarks + raw counts), same numbering as the
                  .docx. Section 1 (the file's own "Summary" section) is
                  computed from the other rows: Fail if any table failed.
  3. Rollup    -- Pass / Fail counts per member (RESULT_SCAN of statement 2).

Per-table section queries are copied verbatim. Sections listed in SKIP are
left out (their vault table cannot be queried) and named in the file header.

    python3 BGIL_DBT/validation/tools/build_dm_t1_travel_summary.py
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from tag_travel_members import member_buckets  # noqa: E402
from build_dm_t2_travel_consolidated import (  # noqa: E402
    sections, indent, lit, columns_used)

DMT = HERE.parent / "travel" / "DM-T"
PROJECTS = ["OPUS", "MAXIMUS"]

METRICS = ["rows_in_scope", "null_load_datetime", "null_record_source", "null_dbt_run_ts",
           "placeholder_load_datetime", "future_load_datetime", "load_after_run_ts",
           "unexpected_record_source"]

# Sections whose vault table cannot be queried (found by the DM-T2 preflight).
SKIP = {
    "MAXIMUS": {
        107: "SAT_AUG_QUOTE_HEADER table does not exist in BGIL_DATA_MODEL (not built yet)",
    },
}


def branch(project, no, member, label, sql):
    have = set(re.findall(r"\bas (\w+)\s*,?\s*$", sql, re.M))
    missing = set(METRICS + ["status", "unexpected_examples"]) - have
    assert not missing, f"{project} section {no}: missing {missing}"
    remarks = ", ".join(f"iff({c} > 0, '{c}=' || {c}, null)"
                        for c in METRICS if c != "rows_in_scope")
    return f"""select {no} as section_no, '{project}' as project, '{member}' as member,
       table_type, {lit(label)} as section_object,
       {", ".join(METRICS)},
       iff(status = 'FAIL', 1, 0) as failing_rows,
       status,
       nullif(array_to_string(array_construct_compact(
           iff(rows_in_scope = 0, '0 rows in scope', null),
           {remarks},
           iff(array_size(unexpected_examples) > 0,
               'unexpected examples: ' || array_to_string(unexpected_examples, ', '), null)), '; '), '') as remarks
  from (
{indent(sql)}
  )"""


def render(project, part, total, summary_label, summary_member, cols, branches, skipped):
    values = ",\n".join(f"    ({no}, {lit(t)}, {lit(c)})"
                        for (t, c), no in sorted(cols.items(), key=lambda x: (x[1], x[0])))
    note = ""
    if skipped:
        note = ("\n   NOT IN THIS QUERY (vault table cannot be queried):\n" +
                "".join(f"     section {no}: {why}\n" for no, why in skipped))
    union = "\n\nunion all\n\n".join(branches)
    cols_out = ", ".join(METRICS)
    summary_sql = ""
    if summary_label:
        summary_sql = f"""
union all
select 1, '{project}', '{summary_member}', 'summary', {lit(summary_label)},
       iff(count_if(status = 'FAIL') = 0, 'Pass', 'Fail'),
       count_if(status = 'FAIL'),
       'tables checked=' || count(*) || '; failed=' || count_if(status = 'FAIL'),
       {", ".join("null" for _ in METRICS)}
  from r"""
    scope = (f"plus section 1 (summary) computed from them" if summary_label else
             "section 1 (summary) is not in this part; it is derived from all parts when the "
             "docx is filled")
    return f"""/* =====================================================================================
   DM-T1  |  Load Audit - Load Metadata Populated (Travel LOB)  -- {project} {part} SUMMARY RUN
   One query for {total} table sections of DM-T1_{project}.sql;
   {scope}. section_no matches the .docx.

   GENERATED by validation/tools/build_dm_t1_travel_summary.py from
   DM-T1_{project}.sql -- regenerate, do not edit by hand.
{note}
   Run order (Snowflake worksheet, one statement at a time):
     1. Preflight -- must return 0 rows. Any row = table/column missing, statement 2 will fail.
     2. Main      -- one row per section. Doc mapping: result -> "Result (Pass / Fail / NA)",
                     failing_rows -> "Rows with status = FAIL (count)", remarks -> "Remarks".
     3. Rollup    -- PASS / FAIL counts per member (run right after statement 2).
   ===================================================================================== */


-- 1. Preflight: tables / columns the sections read that are missing in BGIL_DATA_MODEL --
-- Must return 0 rows. Each row names the first section that would fail to compile.
select v.column1 as section_no, v.column2 as table_name, v.column3 as column_name,
       iff(t.table_name is null, 'TABLE MISSING', 'COLUMN MISSING') as problem
  from (values
{values}
  ) v
  left join (select distinct table_name
               from BAGIC_PREPROD_CURATED_DB.INFORMATION_SCHEMA.TABLES
              where table_schema = 'BGIL_DATA_MODEL') t
    on t.table_name = v.column2
  left join BAGIC_PREPROD_CURATED_DB.INFORMATION_SCHEMA.COLUMNS c
    on c.table_schema = 'BGIL_DATA_MODEL' and c.table_name = v.column2 and c.column_name = v.column3
 where c.column_name is null
 order by 1, 2, 3;


-- 2. Main: all sections ------------------------------------------------------------------
with r as (

{union}

)
select section_no, project, member, table_type, section_object,
       initcap(status) as result, failing_rows, remarks, {cols_out}
  from r{summary_sql}
 order by 1;


-- 3. Rollup (run right after statement 2) -------------------------------------------------
select "MEMBER" as member,
       count(*) as sections,
       count_if("RESULT" = 'Pass') as pass,
       count_if("RESULT" = 'Fail') as fail,
       count_if("ROWS_IN_SCOPE" = 0) as zero_row_sections
  from table(result_scan(last_query_id()))
 group by rollup ("MEMBER")
 order by "MEMBER" nulls last;
"""


# Output files. MAXIMUS is split so no statement nears Snowflake's ~1 MB query
# text limit: (part name, table kinds, section range or None).
PARTS = {
    "OPUS": [("ALL", {"hub", "link", "satellite"}, None)],
    "MAXIMUS": [("HUBS_LINKS", {"hub", "link"}, None),
                ("SATS_PART1", {"satellite"}, (1, 125)),
                ("SATS_PART2", {"satellite"}, (126, 10_000))],
}


def main():
    for project in PROJECTS:
        path = DMT / f"DM-T1_{project}.sql"
        secs = list(sections(path))
        nums = [s[0] for s in secs]
        assert nums == list(range(1, len(secs) + 1)), f"{path.name}: gaps"
        members = member_buckets(len(secs))
        skip = SKIP.get(project, {})
        summary_label, summary_member = secs[0][1], members[0]
        covered = set()
        for part, kinds, rng in PARTS[project]:
            branches, cols, skipped = [], {}, []
            for (no, label, sql), mem in zip(secs, members):
                if no == 1:
                    continue
                kind = re.search(r"'(hub|link|satellite)' as table_type", sql).group(1)
                if kind not in kinds or (rng and not rng[0] <= no <= rng[1]):
                    continue
                covered.add(no)
                if no in skip:
                    skipped.append((no, skip[no]))
                    continue
                branches.append(branch(project, no, mem, label, sql))
                for tc in columns_used(sql):
                    cols.setdefault(tc, no)
            whole = len(PARTS[project]) == 1
            name = "" if whole else f"_{part}"
            out = DMT / f"DM-T1_{project}{name}_SUMMARY.sql"
            out.write_text(render(project, part if not whole else "", len(branches),
                                  summary_label if whole else None, summary_member,
                                  cols, branches, skipped))
            main_bytes = len(out.read_text().split("-- 2. Main")[1].split("-- 3. Rollup")[0])
            print(f"wrote {out.relative_to(HERE.parent)}: {len(branches)} sections, "
                  f"statement 2 = {main_bytes:,} bytes")
        assert covered == set(nums) - {1}, f"{project}: sections not in any part"


if __name__ == "__main__":
    main()
