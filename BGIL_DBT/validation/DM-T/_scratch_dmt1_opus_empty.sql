/* =====================================================================================
   SCRATCH diagnostic -- DM-T1 / OPUS: the 13 vault tables with ZERO rows in scope
   -------------------------------------------------------------------------------------
   Not evidence, not generated by gen_dm_t.py. Delete once the 13 are explained.

   Already ruled out by code inspection (no query needed):
     - Record source tag: every one of the ~230 stg2 models in opus_partner_dv_dbt writes
       a RECORD_SOURCE literal starting 'OPUS_'. No model is disabled, none is missing,
       none has an alias. So ZERO rows in scope means zero rows LOADED, not mis-tagged.
     - Incremental watermark: sat_multi_source / ma_sat_multi_source scope
       MAX(DBT_RUN_TS) with WHERE RECORD_SOURCE LIKE 'OPUS_%'. With no OPUS rows present
       that returns the 1900-01-01 sentinel, i.e. a full load. It cannot starve itself.

   So the remaining explanations are: (a) the model never ran, or (b) every candidate row
   is dropped by a WHERE in the vault macro -- src_pk IS NOT NULL, the
   LOAD_DATETIME window, or (ma_sat) a NULL child key.

   Query A answers (a). Query B answers (b).
   ===================================================================================== */


----------------------------------------------------------------------------------------
-- A. Did these 13 models ever run?  (project pre/post-hook writes this log on target=dev)
-- A model absent from this list has never been built on dev -> that IS the answer for it.
----------------------------------------------------------------------------------------
select upper(model_name) as model_name,
       count(*) as run_count,
       max(run_start_timestamp) as last_run,
       max_by(status, run_start_timestamp) as last_status,
       max_by(target_table, run_start_timestamp) as target_table
  from BAGIC_PREPROD_CURATED_DB.UTILS.MAXI_RAW_DBT_MODEL_RUN_LOG
 where upper(model_name) in (
           'LNK_PARTY_LOCATION',
           'SAT_AUG_CHANNEL',
           'SAT_AUG_KYC_DOCUMENT',
           'SAT_AUG_KYC_LOCATION',
           'SAT_AUG_KYC_PARTY',
           'SAT_AUG_KYC_POLICY',
           'SAT_AUG_LNK_ROLE_PROVIDER',
           'SAT_AUG_LOCATION',
           'SAT_AUG_PARTY',
           'SAT_AUG_POLICY',
           'SAT_LNK_PARTY_ROLE_CORE',
           'SAT_POLICY_CLASSIFICATION',
           'SAT_POLICY_PREMIUM_SUMMARY'
       )
 group by 1
 order by 1;


