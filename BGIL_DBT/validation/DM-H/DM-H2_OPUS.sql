-- 33. OPUS — CDC result (all satellites)   [Implemented]
-- Joins the BEFORE and AFTER captures of the same run id. raw_changed compares the
-- normalised RAW payload hash (same UPPER/TRIM/NULL rules as the HASHDIFF, so a
-- case-only RAW edit is not a change); new_rows = satellite rows added for the key
-- between the captures.
----------------------------------------------------------------------------------------
with b as (select * from BAGIC_PREPROD_CURATED_DB.BGIL_VALIDATION.DM_H_CDC_SNAPSHOT where run_id = $DM_H_RUN and phase = 'BEFORE' and project = 'OPUS'),
     a as (select * from BAGIC_PREPROD_CURATED_DB.BGIL_VALIDATION.DM_H_CDC_SNAPSHOT where run_id = $DM_H_RUN and phase = 'AFTER'  and project = 'OPUS'),
     k as (
    select b.satellite, b.record_source, b.hkey, b.cdk,
           not equal_null(b.raw_hash, a.raw_hash) as raw_changed,
           a.sat_rows - b.sat_rows as new_rows
      from b join a
        on a.satellite = b.satellite and a.record_source = b.record_source
       and a.hkey = b.hkey and equal_null(a.cdk, b.cdk)
)
select 'OPUS' as project, satellite, record_source,
       count(*) as unchanged_keys,
       count_if(new_rows = 0) as unchanged_no_new_row,
       count_if(new_rows <> 0) as unchanged_with_new_row,
       iff(unchanged_with_new_row = 0, 'PASS', 'FAIL') as status
  from k
 where not raw_changed
 group by satellite, record_source
 order by iff(status = 'FAIL', 0, 1), satellite, record_source;
