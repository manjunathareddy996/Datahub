-- 7. OPUS — Re-load test: result   [Implemented]
-- Compares the BEFORE / AFTER row counts of the same run id.
----------------------------------------------------------------------------------------
select b.project, b.satellite, b.row_count as rows_before, a.row_count as rows_after,
       a.row_count - b.row_count as rows_added,
       iff(rows_added = 0, 'PASS', 'FAIL') as status
  from BAGIC_PREPROD_CURATED_DB.UTILS.DM_H_RELOAD_SNAPSHOT b
  join BAGIC_PREPROD_CURATED_DB.UTILS.DM_H_RELOAD_SNAPSHOT a
    on a.run_id = b.run_id and a.satellite = b.satellite and a.phase = 'AFTER'
 where b.run_id = $DM_H_RUN and b.phase = 'BEFORE' and b.project = 'OPUS'
 order by iff(status = 'FAIL', 0, 1), b.satellite;
