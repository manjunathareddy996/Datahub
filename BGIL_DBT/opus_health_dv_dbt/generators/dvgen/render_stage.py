def render_bridge(artifact: Artifact) -> str:
    """Render a ``bridge_<stem>__<hub>`` view."""
    if artifact.kind != "bridge":
        raise RenderError(f"render_bridge() cannot render kind {artifact.kind!r}")
    data = artifact.data
    what = f"bridge {artifact.name}"
    hub = _code(data, "hub", what, ("HUB_",))
    table = _str(data, "table", what).upper()
    source = _model_name(_str(data, "source_model", what), what)
    notes = _comment_lines(_seq(data, "header_notes", what, False), what)

    aliases = {"t"}
    join_lines: list[str] = []
    via: list[str] = []
    for i, join in enumerate(_seq(data, "joins", what)):
        where = f"{what}.joins[{i}]"
        if not isinstance(join, Mapping):
            raise RenderError(f"{where}: must be an object")
        model = _model_name(_str(join, "model", where), where)
        alias = _str(join, "alias", where)
        if not _LOWER_IDENT.match(alias) or alias in aliases:
            raise RenderError(f"{where}: alias {alias!r} is invalid or reused")
        aliases.add(alias)
        conds = []
        for j, cond in enumerate(_seq(join, "on", where)):
            cw = f"{where}.on[{j}]"
            if not isinstance(cond, Mapping):
                raise RenderError(f"{cw}: must be an object")
            left = _one_line(_str(cond, "left", cw), cw)
            right = _one_line(_str(cond, "right", cw), cw)
            conds.append(f"{left} = {right}")
        join_lines.append(f"inner join {{{{ ref('{model}') }}}} as {alias}")
        join_lines.append(f"    on {conds[0]}")
        join_lines.extend(f"    and {cond}" for cond in conds[1:])
        via.append(model)

    selects = ["    t.*"]
    seen: set[str] = set()
    for i, entry in enumerate(_seq(data, "columns", what)):
        where = f"{what}.columns[{i}]"
        if not isinstance(entry, Mapping):
            raise RenderError(f"{where}: must be an object")
        col = _str(entry, "column", where)
        if not _LOWER_IDENT.match(col) or col in seen:
            raise RenderError(f"{where}: column {col!r} is invalid or reused")
        seen.add(col)
        selects.append(f"    {_one_line(_str(entry, 'expr', where), where)} as {col}")

    header = [
        f"-- HEALTH bridge view for {hub} on table '{table}': every column of "
        f"{source}",
        f"-- plus the {hub} key column(s) from {', '.join(via)}, joined on the "
        f"shared key.",
        "-- The join can be many-to-many: a row of the table that matches "
        "several bridge rows",
        "-- appears once per match, and a row with no match is dropped "
        "(inner join).",
        *notes,
    ]
    body = ["select", ",\n".join(selects),
            f"from {{{{ ref('{source}') }}}} as t", *join_lines]
    text = "\n".join([_CONFIG, "", generated_header(RENDERER), *header, "",
                      *body])
    return text.rstrip("\n") + "\n"


def render(artifact: Artifact) -> str:
    """Dispatch on ``artifact.kind`` (stage kinds and ``bridge``)."""
    if artifact.kind == "bridge":
        return render_bridge(artifact)
    return render_stage(artifact)
