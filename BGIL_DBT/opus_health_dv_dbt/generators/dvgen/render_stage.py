"""Render Stg2 stage models and bridge views (design "Render modules", Q10).

Every function here is pure: it reads one ``Artifact`` and returns the file
text. Output uses ``\\n`` line endings, ends with exactly one newline and
contains no timestamps, run ids or absolute paths. The body of a stage model
(from ``{%- set yaml_metadata -%}`` to the end) has the same shape as the
Template_Project stage models, for example
``opus_partner_dv_dbt/models/raw_vault/standard/staging/stg2_hub_cp_partners__party.sql``.

Stage kinds and their file shape
================================

``stage_hub``::

    {{ config(materialized='view') }}

    -- GENERATED by dvgen (render_stage); do not hand-edit.
    -- HEALTH STANDARD-MODEL per-table stage() for HUB_CLAIM, table 'T'.
    -- <header_notes>

    {%- set yaml_metadata -%}
    source_model: 'stg_health__t'
    hashed_columns:
      CLAIM_HKEY: 'PARENT_NK'
    derived_columns:
      PARENT_BK: 'claim_id'
      PARENT_NK: "'HUB_CLAIM|' || (claim_id)"
      LOAD_DATETIME: 'INC_JOB_UPDATED_AT'
      RECORD_SOURCE: '!OPUS_T'
    {%- endset -%}
    ...automate_dv.stage(include_source_columns=false, ...)

``stage_link``: one ``<HUB>_HKEY_NK`` derived column per hub
(``"'HUB_PARTY|' || part_id"``) and one ``<LINK>_HKEY_NK``
(``"'LNK_CLAIM_PARTY|' || part_id || '|' || claim_id"``), each hashed into
its ``_HKEY`` column. Hubs appear in ``hub_keys`` order everywhere.

``stage_sat`` / ``stage_aug``: the hub (or link) key as ``PARENT_BK`` /
``PARENT_NK`` hashed into the parent's ``_HKEY``, plus ``HASHDIFF``
(``is_hashdiff: true``) over the sorted child-key and payload columns, then
the child-key derived columns (in the given order) and the payload derived
columns (sorted by column). ``stage_aug`` differs only in the header line
(``HEALTH AUGMENTED``).

``bridge``: a plain view ``bridge_<stem>__<hub>`` that selects every column
of the table's stg1 model plus the hub's key column(s) from the joined
model(s). The header says the join can be many-to-many.

Artifact.data contract
======================

All values are plain JSON (strings, lists, objects). ``Artifact.data`` is a
``FrozenDict``, so lists arrive as tuples. Keys not listed are ignored.

Common to every ``stage_*`` kind:

- ``target`` (str): vault code the stage feeds, used in the header
  (``HUB_CLAIM``, ``LNK_CLAIM_PARTY``, ``SAT_CLAIM_NOTE``).
- ``source_model`` (str): dbt model the stage reads, the table's stg1 model
  or a ``bridge_*`` model.
- ``table`` (str): physical source table name.
- ``record_source`` (str): ``naming.record_source(prefix, table)``, that is
  ``'!' + RECORD_SOURCE_PREFIX + TABLE``. Must start with ``!`` and end with
  the upper-cased table name.
- ``load_datetime`` (str): ``naming.watermark_for(table, WATERMARK_COLUMN,
  WATERMARK_OVERRIDES)``. Rendered upper-cased, as a column reference (a
  leading ``!`` is refused).
- ``parent_code`` (str): ``HUB_*`` (hub, sat, aug) or ``LNK_*`` (link, or a
  sat/aug on a link).
- ``hkey`` (str, optional): must equal ``naming.hkey(parent_code)`` if given.
- ``header_notes`` (list[str], optional): extra header comment lines (key
  provenance, coalesce sources with row ids, child-key origin, ...).

``stage_hub``:

- ``parent_bk`` (str): raw business key over stg1 aliases
  (``keys.raw_key``). ``PARENT_NK`` is ``keys.parent_nk(parent_code,
  parent_bk)``.

``stage_link``:

- ``hub_keys`` (list of ``{"code": "HUB_X", "raw": "<raw key>"}``): ordered.
  The planner supplies the order: the Template_Project link model's
  ``src_fk`` order when the template has the link, else sorted hub codes.
  This module never re-sorts it. ``<LINK>_HKEY_NK`` is
  ``keys.link_nk(parent_code, raw_by_hub, hub_order=<that order>)``.

``stage_sat`` / ``stage_aug``:

- Hub parent: ``parent_bk`` as for ``stage_hub``.
- Link parent: ``hub_keys`` as for ``stage_link``. ``PARENT_NK`` is the
  link key; ``PARENT_BK`` is the raw components joined with ``'|'``.
- ``payload`` (non-empty list of ``{"column", "expr", "sql_type_for_null"}``):
  ``column`` is the payload column (``naming.payload_column``). ``expr`` is a
  string (an stg1 alias or expression), a list of strings (fallback fan-in,
  rendered ``coalesce(a, b, c)`` in the given order) or ``null`` (column not
  carried by this table, rendered ``cast(null as <sql_type_for_null>)``,
  default ``varchar``).
- ``childkey`` (list, optional, multi-active only) of ``{"column",
  "literal"}`` (rendered as the AutomateDV constant ``'!<literal>'``) or
  ``{"column", "expr"}`` (rendered as the expression).

``bridge``:

- ``hub`` (str): the hub whose key the bridge adds.
- ``table`` (str): the physical table T the bridge extends.
- ``source_model`` (str): T's stg1 model, aliased ``t``.
- ``joins`` (non-empty ordered list of ``{"model", "alias", "on"}``):
  ``on`` is a non-empty list of ``{"left", "right"}`` SQL operands joined
  with ``=`` and ``and``. Several joins express a MAXIMUS spine walk.
- ``columns`` (non-empty list of ``{"column", "expr"}``): the hub key
  columns selected from the joined models, rendered ``<expr> as <column>``.
- ``header_notes`` (list[str], optional).

This module is project-agnostic and is copied byte-for-byte into the sibling
Health_Project.

Requirements 5.1, 5.2, 5.3, 5.5, 5.8, 6.2, 6.8, 7.3.
"""
from __future__ import annotations

import re
from collections.abc import Mapping, Sequence
from typing import Any

from . import naming
from .emit import generated_header
from .keys import _link_component, link_nk, parent_nk
from .model import Artifact

__all__ = [
    "RenderError",
    "STAGE_KINDS",
    "render_stage",
    "render_bridge",
    "render",
]

RENDERER = "render_stage"
STAGE_KINDS = ("stage_hub", "stage_link", "stage_sat", "stage_aug")

_CONFIG = "{{ config(materialized='view') }}"
_STAGE_CALL = (
    "{% set metadata_dict = fromyaml(yaml_metadata) %}\n"
    "\n"
    "{{ automate_dv.stage(include_source_columns=false,\n"
    "                      source_model=metadata_dict['source_model'],\n"
    "                      hashed_columns=metadata_dict['hashed_columns'],\n"
    "                      derived_columns=metadata_dict['derived_columns']) }}\n"
)

_UPPER_COL = re.compile(r"[A-Z][A-Z0-9_]*\Z")
_LOWER_IDENT = re.compile(r"[a-z_][a-z0-9_]*\Z")
_MODEL = re.compile(r"[a-z][a-z0-9_]*\Z")
_SQL_TYPE = re.compile(r"[A-Za-z][A-Za-z0-9_]*(\(\s*\d+(\s*,\s*\d+)?\s*\))?\Z")
_JINJA = ("{{", "}}", "{%", "%}", "{#", "#}")
_RESERVED = frozenset({"PARENT_BK", "PARENT_NK", "HASHDIFF", "LOAD_DATETIME",
                       "RECORD_SOURCE"})


class RenderError(ValueError):
    """An artifact's data does not fit the render_stage contract."""


# --------------------------------------------------------------------------
# Small helpers
# --------------------------------------------------------------------------

def _get(data: Mapping[str, Any], key: str, what: str) -> Any:
    if key not in data or data[key] is None:
        raise RenderError(f"{what}: missing {key!r}")
    return data[key]


def _str(data: Mapping[str, Any], key: str, what: str) -> str:
    value = _get(data, key, what)
    if not isinstance(value, str) or not value.strip():
        raise RenderError(f"{what}: {key!r} must be a non-empty string")
    return value.strip()


def _seq(data: Mapping[str, Any], key: str, what: str,
         required: bool = True) -> Sequence[Any]:
    value = data.get(key)
    if value is None:
        if required:
            raise RenderError(f"{what}: missing {key!r}")
        return ()
    if isinstance(value, (str, bytes)) or not isinstance(value, Sequence):
        raise RenderError(f"{what}: {key!r} must be a list")
    if required and not value:
        raise RenderError(f"{what}: {key!r} is empty")
    return value


def _one_line(text: str, what: str) -> str:
    if "\n" in text or "\r" in text:
        raise RenderError(f"{what}: value must be on one line: {text!r}")
    for token in _JINJA:
        if token in text:
            raise RenderError(f"{what}: Jinja delimiter {token!r} in {text!r}")
    return text


def _yq(value: str, what: str = "yaml value") -> str:
    """YAML scalar as the template writes it.

    Single quotes unless the value contains a single quote, then double
    quotes (with ``\\`` and ``"`` escaped).
    """
    _one_line(value, what)
    if "'" not in value:
        return f"'{value}'"
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def _comment_lines(notes: Sequence[Any], what: str) -> list[str]:
    """Header notes as ``--`` lines; Jinja delimiters are defused."""
    lines: list[str] = []
    for note in notes:
        if not isinstance(note, str):
            raise RenderError(f"{what}: header note must be a string: {note!r}")
        for raw in note.replace("\r\n", "\n").replace("\r", "\n").split("\n"):
            text = raw.rstrip()
            for token in _JINJA:
                text = text.replace(token, f"{token[0]} {token[1]}")
            lines.append(f"-- {text}" if text else "--")
    return lines


def _column(name: Any, what: str) -> str:
    if not isinstance(name, str) or not _UPPER_COL.match(name):
        raise RenderError(f"{what}: column {name!r} must be UPPER_SNAKE")
    return name


def _model_name(name: str, what: str) -> str:
    if not _MODEL.match(name):
        raise RenderError(f"{what}: model name {name!r} is not a dbt model name")
    return name


def _code(data: Mapping[str, Any], key: str, what: str,
          prefixes: tuple[str, ...]) -> str:
    code = _str(data, key, what).upper()
    if not code.startswith(prefixes) or not re.match(r"[A-Z][A-Z0-9_]*\Z", code):
        raise RenderError(f"{what}: {key}={code!r} must start with {prefixes}")
    return code


def _hkey(data: Mapping[str, Any], parent: str, what: str) -> str:
    try:
        expected = naming.hkey(parent)
    except naming.NamingError as exc:
        raise RenderError(f"{what}: {exc}") from None
    given = data.get("hkey")
    if given is not None and given != expected:
        raise RenderError(f"{what}: hkey {given!r} != {expected!r} for {parent}")
    return expected


def _hub_keys(data: Mapping[str, Any], what: str) -> list[tuple[str, str]]:
    out: list[tuple[str, str]] = []
    for i, entry in enumerate(_seq(data, "hub_keys", what)):
        where = f"{what}.hub_keys[{i}]"
        if not isinstance(entry, Mapping):
            raise RenderError(f"{where}: must be an object")
        code = _code(entry, "code", where, ("HUB_",))
        raw = _one_line(_str(entry, "raw", where), where)
        if code in (c for c, _ in out):
            raise RenderError(f"{what}: hub {code} listed twice in hub_keys")
        out.append((code, raw))
    return out


def _link_key(link: str, hubs: list[tuple[str, str]], what: str) -> str:
    try:
        return link_nk(link, dict(hubs), hub_order=[c for c, _ in hubs])
    except ValueError as exc:
        raise RenderError(f"{what}: {exc}") from None


def _parent_nk(code: str, raw: str, what: str) -> str:
    try:
        return parent_nk(code, raw)
    except ValueError as exc:
        raise RenderError(f"{what}: {exc}") from None


