def _common(artifact: Artifact) -> dict[str, Any]:
    data = artifact.data
    what = f"{artifact.kind} {artifact.name}"
    table = _str(data, "table", what).upper()
    record_source = _one_line(_str(data, "record_source", what), what)
    if not record_source.startswith("!") or not record_source.endswith(table):
        raise RenderError(
            f"{what}: record_source {record_source!r} must be '!' + prefix + "
            f"{table}")
    ldts = _one_line(_str(data, "load_datetime", what), what)
    if ldts.startswith("!"):
        raise RenderError(f"{what}: load_datetime must be a column, not {ldts!r}")
    if not _UPPER_COL.match(ldts.upper()):
        raise RenderError(f"{what}: load_datetime {ldts!r} is not a column name")
    return {
        "what": what,
        "target": _one_line(_str(data, "target", what), what),
        "table": table,
        "source_model": _model_name(_str(data, "source_model", what), what),
        "record_source": record_source,
        "load_datetime": ldts.upper(),
        "notes": _comment_lines(_seq(data, "header_notes", what, False), what),
    }


def _payload_expr(entry: Mapping[str, Any], where: str) -> str:
    expr = entry.get("expr")
    if expr is None:
        sql_type = entry.get("sql_type_for_null") or "varchar"
        if not isinstance(sql_type, str) or not _SQL_TYPE.match(sql_type):
            raise RenderError(f"{where}: bad sql_type_for_null {sql_type!r}")
        return f"cast(null as {sql_type})"
    if isinstance(expr, str):
        if not expr.strip():
            raise RenderError(f"{where}: expr is empty")
        return _one_line(expr.strip(), where)
    if isinstance(expr, Sequence):
        parts = []
        for part in expr:
            if not isinstance(part, str) or not part.strip():
                raise RenderError(f"{where}: coalesce part {part!r} is empty")
            parts.append(_one_line(part.strip(), where))
        if not parts:
            raise RenderError(f"{where}: coalesce list is empty")
        if len(parts) == 1:
            return parts[0]
        return f"coalesce({', '.join(parts)})"
    raise RenderError(f"{where}: expr must be a string, a list or null")


def _childkey_expr(entry: Mapping[str, Any], where: str) -> str:
    has_literal = entry.get("literal") is not None
    has_expr = entry.get("expr") is not None
    if has_literal == has_expr:
        raise RenderError(f"{where}: give exactly one of 'literal' or 'expr'")
    if has_literal:
        literal = entry["literal"]
        if not isinstance(literal, str) or not literal.strip():
            raise RenderError(f"{where}: literal must be a non-empty string")
        return "!" + _one_line(literal, where)
    expr = entry["expr"]
    if not isinstance(expr, str) or not expr.strip():
        raise RenderError(f"{where}: expr must be a non-empty string")
    return _one_line(expr.strip(), where)


def _yaml_block(source_model: str, hashed: list[tuple[str, Any]],
                derived: list[tuple[str, str]]) -> list[str]:
    lines = ["{%- set yaml_metadata -%}",
             f"source_model: {_yq(source_model)}",
             "hashed_columns:"]
    for name, value in hashed:
        if isinstance(value, str):
            lines.append(f"  {name}: {_yq(value)}")
        else:  # HASHDIFF column list
            lines.append(f"  {name}:")
            lines.append("    is_hashdiff: true")
            lines.append("    columns:")
            lines.extend(f"      - {_yq(c)}" for c in value)
    lines.append("derived_columns:")
    lines.extend(f"  {name}: {_yq(value, name)}" for name, value in derived)
    lines.append("{%- endset -%}")
    return lines


def _assemble(header: list[str], body: list[str]) -> str:
    text = "\n".join([_CONFIG, "", generated_header(RENDERER), *header, "",
                      *body, "", _STAGE_CALL])
    return text.rstrip("\n") + "\n"


def _check_unique(columns: list[str], reserved: set[str], what: str) -> None:
    seen: set[str] = set()
    for col in columns:
        if col in reserved or col in seen:
            raise RenderError(f"{what}: column {col} is duplicated or reserved")
        seen.add(col)


def _render_hub(artifact: Artifact, c: dict[str, Any]) -> str:
    what = c["what"]
    parent = _code(artifact.data, "parent_code", what, ("HUB_",))
    hk = _hkey(artifact.data, parent, what)
    bk = _one_line(_str(artifact.data, "parent_bk", what), what)
    hashed = [(hk, "PARENT_NK")]
    derived = [("PARENT_BK", bk), ("PARENT_NK", _parent_nk(parent, bk, what)),
               ("LOAD_DATETIME", c["load_datetime"]),
               ("RECORD_SOURCE", c["record_source"])]
    header = [f"-- HEALTH STANDARD-MODEL per-table stage() for {c['target']}, "
              f"table '{c['table']}'.", *c["notes"]]
    return _assemble(header, _yaml_block(c["source_model"], hashed, derived))


def _render_link(artifact: Artifact, c: dict[str, Any]) -> str:
    what = c["what"]
    link = _code(artifact.data, "parent_code", what, ("LNK_",))
    link_hk = _hkey(artifact.data, link, what)
    hubs = _hub_keys(artifact.data, what)
    hashed: list[tuple[str, Any]] = []
    derived: list[tuple[str, str]] = []
    for code, raw in hubs:
        hk = naming.hkey(code)
        hashed.append((hk, f"{hk}_NK"))
        derived.append((f"{hk}_NK", f"'{code}|' || {_link_component(raw)}"))
    if link_hk in (h for h, _ in hashed):
        raise RenderError(f"{what}: link hkey {link_hk} clashes with a hub hkey")
    hashed.append((link_hk, f"{link_hk}_NK"))
    derived.append((f"{link_hk}_NK", _link_key(link, hubs, what)))
    derived += [("LOAD_DATETIME", c["load_datetime"]),
                ("RECORD_SOURCE", c["record_source"])]
    header = [f"-- HEALTH STANDARD-MODEL per-table stage() for {c['target']}, "
              f"table '{c['table']}'.",
              "-- Link key components in hub order: "
              + ", ".join(code for code, _ in hubs) + ".",
              *c["notes"]]
    return _assemble(header, _yaml_block(c["source_model"], hashed, derived))


def _render_sat(artifact: Artifact, c: dict[str, Any], augmented: bool) -> str:
    data = artifact.data
    what = c["what"]
    parent = _code(data, "parent_code", what, ("HUB_", "LNK_"))
    hk = _hkey(data, parent, what)
    if parent.startswith("HUB_"):
        bk = _one_line(_str(data, "parent_bk", what), what)
        nk = _parent_nk(parent, bk, what)
    else:
        hubs = _hub_keys(data, what)
        bk = " || '|' || ".join(_link_component(raw) for _, raw in hubs)
        nk = _link_key(parent, hubs, what)

    childkeys: list[tuple[str, str]] = []
    for i, entry in enumerate(_seq(data, "childkey", what, False)):
        where = f"{what}.childkey[{i}]"
        if not isinstance(entry, Mapping):
            raise RenderError(f"{where}: must be an object")
        childkeys.append((_column(entry.get("column"), where),
                          _childkey_expr(entry, where)))
    payload: list[tuple[str, str]] = []
    for i, entry in enumerate(_seq(data, "payload", what)):
        where = f"{what}.payload[{i}]"
        if not isinstance(entry, Mapping):
            raise RenderError(f"{where}: must be an object")
        payload.append((_column(entry.get("column"), where),
                        _payload_expr(entry, where)))
    payload.sort(key=lambda p: p[0])
    _check_unique([col for col, _ in childkeys + payload], {*_RESERVED, hk},
                  what)

    hashdiff = sorted(col for col, _ in childkeys + payload)
    hashed: list[tuple[str, Any]] = [(hk, "PARENT_NK"), ("HASHDIFF", hashdiff)]
    derived = [("PARENT_BK", bk), ("PARENT_NK", nk), *childkeys, *payload,
               ("LOAD_DATETIME", c["load_datetime"]),
               ("RECORD_SOURCE", c["record_source"])]
    track = "AUGMENTED" if augmented else "STANDARD-MODEL"
    header = [f"-- HEALTH {track} per-table stage() for {c['target']}, "
              f"table '{c['table']}'.", *c["notes"]]
    return _assemble(header, _yaml_block(c["source_model"], hashed, derived))


def render_stage(artifact: Artifact) -> str:
    """Render a ``stage_hub``, ``stage_link``, ``stage_sat`` or ``stage_aug``."""
    if artifact.kind not in STAGE_KINDS:
        raise RenderError(f"render_stage() cannot render kind {artifact.kind!r}")
    c = _common(artifact)
    if artifact.kind == "stage_hub":
        return _render_hub(artifact, c)
    if artifact.kind == "stage_link":
        return _render_link(artifact, c)
    return _render_sat(artifact, c, augmented=artifact.kind == "stage_aug")


