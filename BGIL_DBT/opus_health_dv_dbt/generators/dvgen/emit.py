"""Guarded file emission, write manifest and stale-model cleanup.

``WriteGuard`` is the only way the Builder writes files. Every write is
resolved against the project root and refused with ``OutsideProject``
unless it lands inside that root (Requirement 10.3). Text is written as
UTF-8 with ``\\n`` line endings and its sha256 is recorded in the write
manifest (Requirements 10.1, 10.2).

After emitting, ``remove_stale`` deletes every file under ``models/`` that
the current plan did not write and that carries the GENERATED header. A
file without the header means someone added a hand-written model, so the
build stops with ``UntrackedModelFile`` naming it, before anything is
deleted.

This module is project-agnostic: the project root is passed in.
"""
from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path
from typing import Iterable, Optional, Union

MANIFEST_REL = "build_artifacts/health_write_manifest.json"
MODELS_REL = "models"

# Comment markers a generated file may use before the header text:
# ``--`` for SQL, ``#`` for YAML.
_HEADER_TEXT = "GENERATED by dvgen ("
_HEADER_MARKERS = ("--", "#")


def generated_header(renderer: str, marker: str = "--") -> str:
    """Return the GENERATED header line (without newline) for a renderer."""
    return f"{marker} {_HEADER_TEXT}{renderer}); do not hand-edit."


def has_generated_header(text: str) -> bool:
    """True when the file starts with the GENERATED header.

    Leading blank lines and one-line Jinja blocks such as
    ``{{ config(materialized='view') }}`` may precede the header.
    """
    for line in text.splitlines():
        s = line.strip()
        if not s or (s.startswith("{{") and s.endswith("}}")):
            continue
        for marker in _HEADER_MARKERS:
            if s.startswith(marker) and s[len(marker):].lstrip().startswith(
                _HEADER_TEXT
            ):
                return True
        return False
    return False


class OutsideProject(PermissionError):
    """A write resolved to a path outside the project root."""

    def __init__(self, rel_path: str, resolved: str, root: str):
        self.rel_path = rel_path
        self.resolved = resolved
        self.root = root
        super().__init__(
            f"refusing to write {rel_path!r}: resolves to {resolved!r}, "
            f"outside project root {root!r}"
        )


class DuplicateWrite(RuntimeError):
    """Two writes in one build targeted the same path with different text."""

    def __init__(self, rel_path: str):
        self.rel_path = rel_path
        super().__init__(
            f"{rel_path!r} was written twice in one build with different content"
        )


class UntrackedModelFile(RuntimeError):
    """A file under models/ is neither planned nor generated by dvgen."""

    def __init__(self, paths: list[str]):
        self.paths = list(paths)
        listing = "\n".join(f"  - {p}" for p in self.paths)
        super().__init__(
            "hand-written file(s) under models/ without the GENERATED header; "
            "move the logic into a generator or delete the file:\n" + listing
        )


def _norm(path: Union[str, Path]) -> str:
    return os.path.normcase(os.path.normpath(str(path)))


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _to_lf(text: str) -> str:
    return text.replace("\r\n", "\n").replace("\r", "\n")


class WriteGuard:
    """Writes files inside one project root and records each write."""

    def __init__(self, project_root: Union[str, Path]):
        self.root = Path(project_root).resolve()
        self._root_norm = _norm(self.root)
        self._written: dict[str, str] = {}  # posix rel path -> sha256

    # -- path handling -----------------------------------------------------

    def resolve(self, rel_path: Union[str, Path]) -> Path:
        """Resolve ``rel_path`` against the root; raise unless inside it."""
        raw = str(rel_path)
        if not raw or "\x00" in raw:
            raise OutsideProject(raw, raw, str(self.root))
        target = (self.root / raw).resolve()
        norm = _norm(target)
        if norm == self._root_norm or not norm.startswith(
            self._root_norm.rstrip(os.sep) + os.sep
        ):
            raise OutsideProject(raw, str(target), str(self.root))
        return target

    def rel(self, path: Path) -> str:
        """Return the posix path of ``path`` relative to the root."""
        return Path(os.path.relpath(str(path), str(self.root))).as_posix()

    # -- writing -----------------------------------------------------------

    def write(self, rel_path: Union[str, Path], text: str) -> str:
        """Write ``text`` as UTF-8 with ``\\n`` endings; return its sha256."""
        target = self.resolve(rel_path)
        data = _to_lf(text).encode("utf-8")
        digest = _sha256(data)
        key = self.rel(target)
        previous = self._written.get(key)
        if previous is not None and previous != digest:
            raise DuplicateWrite(key)
        target.parent.mkdir(parents=True, exist_ok=True)
        with open(target, "wb") as fh:
            fh.write(data)
        self._written[key] = digest
        return digest

    def write_bytes(self, rel_path: Union[str, Path], data: bytes) -> str:
        """Write ``data`` unchanged (no newline conversion); return its sha256.

        Used for byte-exact copies such as the Template_Project macros and
        ``dbt_packages/``, whose digests must equal the source files.
        """
        target = self.resolve(rel_path)
        digest = _sha256(data)
        key = self.rel(target)
        previous = self._written.get(key)
        if previous is not None and previous != digest:
            raise DuplicateWrite(key)
        target.parent.mkdir(parents=True, exist_ok=True)
        with open(target, "wb") as fh:
            fh.write(data)
        self._written[key] = digest
        return digest

    @property
    def written(self) -> dict[str, str]:
        """Sorted copy of every path written so far and its sha256."""
        return dict(sorted(self._written.items()))

    # -- manifest ----------------------------------------------------------

    def manifest_text(self) -> str:
        entries = [{"path": p, "sha256": h} for p, h in self.written.items()]
        return json.dumps({"files": entries}, indent=2, sort_keys=True) + "\n"

    def write_manifest(self, rel_path: str = MANIFEST_REL) -> str:
        """Write the sorted manifest. The manifest does not list itself."""
        target = self.resolve(rel_path)
        data = self.manifest_text().encode("utf-8")
        target.parent.mkdir(parents=True, exist_ok=True)
        with open(target, "wb") as fh:
            fh.write(data)
        return _sha256(data)

    # -- stale-model cleanup ----------------------------------------------

    def remove_stale(
        self,
        planned: Optional[Iterable[Union[str, Path]]] = None,
        models_rel: str = MODELS_REL,
    ) -> list[str]:
        """Delete generated files under ``models/`` that are not planned.

        ``planned`` defaults to every path written so far. Raises
        ``UntrackedModelFile`` naming every unplanned file without the
        GENERATED header; in that case nothing is deleted. Returns the
        sorted relative paths that were removed.
        """
        keep = (
            set(self._written)
            if planned is None
            else {self.rel(self.resolve(p)) for p in planned}
        )
        models_dir = self.resolve(models_rel)
        if not models_dir.is_dir():
            return []
        stale: list[tuple[str, Path]] = []
        untracked: list[str] = []
        for path in sorted(p for p in models_dir.rglob("*") if p.is_file()):
            key = self.rel(path)
            if key in keep:
                continue
            text = path.read_bytes().decode("utf-8", errors="replace")
            if has_generated_header(text):
                stale.append((key, path))
            else:
                untracked.append(key)
        if untracked:
            raise UntrackedModelFile(untracked)
        for key, path in stale:
            self.resolve(key).unlink()
        return [key for key, _ in stale]
