def test_hub_matches_template_hub_claim():
    text = render_vault(Artifact(
        kind="hub", path="models/raw_vault/standard/hubs/hub_claim.sql",
        name="hub_claim",
        data={"hub": "HUB_CLAIM", "src_pk": "CLAIM_HKEY",
              "source_model": ["stg2_hub_clm_interested_parties__claim"]}))
    tpl = _template("hubs/hub_claim.sql")
    _check_common(text)
    assert _body(text) == _body(tpl)
    assert _config(text)[1:] == _config(tpl)


def test_hub_source_model_sorted_and_deduplicated():
    text = render_hub({"hub": "HUB_PARTY", "src_pk": "PARTY_HKEY",
                       "source_model": ["stg2_b", "stg2_a", "stg2_b"]})
    assert "  - 'stg2_a'\n  - 'stg2_b'\nsrc_pk:" in text


def test_link_matches_template_and_keeps_src_fk_order():
    data = {"link": "LNK_CLAIM_PARTY", "src_pk": "CLAIM_PARTY_HKEY",
            "src_fk": ["PARTY_HKEY", "CLAIM_HKEY"],
            "source_model": ["stg2_link_clm_interested_parties__claim_party"]}
    text = render_link(data)
    tpl = _template("links/lnk_claim_party.sql")
    _check_common(text)
    assert _body(text) == _body(tpl)
    assert _config(text)[1:] == _config(tpl)
    assert text.index("'PARTY_HKEY'") < text.index("'CLAIM_HKEY'")


