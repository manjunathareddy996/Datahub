def _design_ma_multi(**over):
    room = "stg2_sat_bjaz_hm_gpa_bill_dtls__claim_benefit_head__room_rent"
    icu = "stg2_sat_bjaz_hm_gpa_bill_dtls__claim_benefit_head__icu_charges"
    data = {"satellite": "SAT_CLAIM_BENEFIT_HEAD",
            "macro": "ma_sat_multi_source", "parent": "HUB_CLAIM",
            "src_pk": "CLAIM_HKEY", "src_cdk": ["BENEFITHEADCODE"],
            "src_payload": ["BENEFITAMOUNT"], "source_model": [room, icu],
            "src_record_source_map": {room: "OPUS", icu: "OPUS"},
            "src_column_map": {room: ["BENEFITAMOUNT"], icu: ["BENEFITAMOUNT"]},
            "unique_key": ["CLAIM_HKEY", "BENEFITHEADCODE", "HASHDIFF",
                           "RECORD_SOURCE"]}
    data.update(over)
    return data


def test_design_example_and_dbt_run_ts_not_passed_to_multi_source():
    text = render_sat(_design_ma_multi(src_extra_columns=["DBT_RUN_TS"]))
    assert "{{ ma_sat_multi_source(src_pk=metadata_dict['src_pk']," in text
    assert "src_cdk=metadata_dict['src_cdk']" in text
    assert "src_extra_columns" not in text
    assert "DBT_RUN_TS" not in text
    assert ("  stg2_sat_bjaz_hm_gpa_bill_dtls__claim_benefit_head__icu_charges:"
            " 'OPUS'") in text
    assert "-- ma_sat_multi_source() for SAT_CLAIM_BENEFIT_HEAD (HUB_CLAIM grain)" in text


def test_multi_source_output_independent_of_input_order():
    a = render_sat(_design_ma_multi())
    data = _design_ma_multi()
    data["source_model"] = list(reversed(data["source_model"]))
    assert render_sat(data) == a


def test_header_lines_are_written_as_comments():
    text = render_sat(_design_ma_multi(header=["literal child key 'Room Rent'"]))
    assert "-- literal child key 'Room Rent'\n" in text


@pytest.mark.parametrize("over, msg", [
    ({"unique_key": ["CLAIM_HKEY", "HASHDIFF"]}, "lacks"),
    ({"src_cdk": []}, "non-empty src_cdk"),
    ({"src_eff": "EFFECTIVE_FROM"}, "src_eff"),
    ({"source_model": ["stg2_only"]}, "two or more"),
    ({"src_column_map": {
        "stg2_sat_bjaz_hm_gpa_bill_dtls__claim_benefit_head__room_rent":
            ["BENEFITAMOUNT"]}}, "keys must equal"),
    ({"src_column_map": {
        "stg2_sat_bjaz_hm_gpa_bill_dtls__claim_benefit_head__room_rent":
            ["OTHER"],
        "stg2_sat_bjaz_hm_gpa_bill_dtls__claim_benefit_head__icu_charges":
            ["BENEFITAMOUNT"]}}, "not in src_payload"),
    ({"src_column_map": {
        "stg2_sat_bjaz_hm_gpa_bill_dtls__claim_benefit_head__room_rent": [],
        "stg2_sat_bjaz_hm_gpa_bill_dtls__claim_benefit_head__icu_charges": []}},
     "come from no source model"),
    ({"macro": "satellite"}, "not in"),
])
def test_multi_source_rejects_bad_data(over, msg):
    with pytest.raises(RenderVaultError, match=msg):
        render_sat(_design_ma_multi(**over))


def test_unique_key_defaults_when_omitted():
    data = _design_ma_multi()
    del data["unique_key"]
    assert render_sat(data) == render_sat(_design_ma_multi())


def test_single_source_rejects_multi_source_fields_and_extra_models():
    base = {"satellite": "SAT_X", "macro": "sat", "src_pk": "X_HKEY",
            "src_payload": ["A"], "source_model": "stg2_x"}
    with pytest.raises(RenderVaultError, match="exactly one"):
        render_sat({**base, "source_model": ["stg2_x", "stg2_y"]})
    with pytest.raises(RenderVaultError, match="takes no unique_key"):
        render_sat({**base, "unique_key": ["X_HKEY", "RECORD_SOURCE"]})
    with pytest.raises(RenderVaultError, match="takes no src_cdk"):
        render_sat({**base, "src_cdk": ["SEQ"]})


def test_link_rejects_duplicate_or_single_fk():
    base = {"link": "LNK_A_B", "src_pk": "A_B_HKEY", "source_model": ["s"]}
    with pytest.raises(RenderVaultError, match="twice"):
        render_link({**base, "src_fk": ["A_HKEY", "A_HKEY"]})
    with pytest.raises(RenderVaultError, match="two or more"):
        render_link({**base, "src_fk": ["A_HKEY"]})


def test_render_vault_rejects_unknown_kind_and_bad_identifier():
    with pytest.raises(RenderVaultError):
        render_vault(Artifact(kind="stage", path="models/x.sql", name="x"))
    with pytest.raises(RenderVaultError, match="plain identifier"):
        render_hub({"hub": "HUB_X", "src_pk": "X HKEY", "source_model": ["s"]})
