"""Unit tests for ``dvgen.render_vault`` (task 5.8).

The shape tests rebuild Template_Project models from artifact data and
compare everything from ``{%- set yaml_metadata -%}`` to the end of the file
(and the config block) with the template file, which is only read.
"""
from __future__ import annotations

from pathlib import Path

import pytest

from dvgen.emit import has_generated_header
from dvgen.model import Artifact
from dvgen.render_vault import (
    RenderVaultError,
    render_hub,
    render_link,
    render_sat,
    render_vault,
)

PROJECT_ROOT = Path(__file__).resolve().parents[2]
TEMPLATE_VAULT = (PROJECT_ROOT.parent / "opus_partner_dv_dbt" / "models"
                  / "raw_vault" / "standard")


def _template(rel: str) -> str:
    path = TEMPLATE_VAULT / rel
    if not path.is_file():
        pytest.skip(f"Template_Project model not found: {path}")
    return path.read_text(encoding="utf-8").replace("\r\n", "\n")


def _body(text: str) -> str:
    return text[text.index("{%- set yaml_metadata -%}"):].rstrip()


def _config(text: str) -> list[str]:
    lines = text.splitlines()
    end = next(i for i, l in enumerate(lines) if l.strip().endswith("}}"))
    return lines[: end + 1]


def _check_common(text: str) -> None:
    assert text.startswith("-- GENERATED by dvgen (render_vault)")
    assert has_generated_header(text)
    assert "\r" not in text
    assert text.endswith("\n") and not text.endswith("\n\n")


