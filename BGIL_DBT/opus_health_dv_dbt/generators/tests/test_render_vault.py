def test_sat_multi_source_matches_template_body_with_merge_config():
    models = ["stg2_sat_bjaz_hm_member_dtls__party_banking",
              "stg2_sat_azbj_partner_extn__party_banking",
              "stg2_sat_bjaz_ctngy_pa_mem_dtls__party_banking",
              "stg2_sat_bjaz_clm_supp_extn__party_banking"]
    data = {"satellite": "SAT_PARTY_BANKING", "macro": "sat_multi_source",
            "src_pk": "PARTY_HKEY", "src_cdk": [],
            "src_payload": ["ACCOUNTNUMBERMASKED", "BANKCODE", "BANKNAME",
                            "IFSCCODE", "MICRCODE"],
            "source_model": models,
            "src_record_source_map": {m: "OPUS_PARTNER" for m in models},
            "src_column_map": {
                models[1]: ["MICRCODE", "ACCOUNTNUMBERMASKED", "IFSCCODE"],
                models[3]: ["ACCOUNTNUMBERMASKED", "BANKNAME"],
                models[2]: ["ACCOUNTNUMBERMASKED", "BANKCODE"],
                models[0]: ["ACCOUNTNUMBERMASKED", "BANKNAME", "MICRCODE"]}}
    text = render_sat(data)
    _check_common(text)
    assert _body(text) == _body(_template("satellites/sat_party_banking.sql"))
    assert _config(text)[1:] == [
        "{{",
        "    config(materialized='incremental', incremental_strategy='merge',",
        "           on_schema_change='append_new_columns',",
        "           unique_key=['PARTY_HKEY', 'HASHDIFF', 'RECORD_SOURCE'])",
        "}}",
    ]


