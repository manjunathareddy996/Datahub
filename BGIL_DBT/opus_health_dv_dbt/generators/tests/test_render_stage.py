def _body(text: str) -> str:
    """From ``{%- set yaml_metadata -%}`` to the end, LF, one trailing newline."""
    text = text.replace("\r\n", "\n")
    return text[text.index("{%- set yaml_metadata -%}"):].rstrip("\n") + "\n"


def _stage(kind: str, name: str, **data) -> Artifact:
    return Artifact(kind=kind, path=f"models/x/{name}.sql", name=name, data=data)


def _check_shape(text: str) -> None:
    assert "\r" not in text
    assert text.endswith("\n") and not text.endswith("\n\n")
    assert text.startswith("{{ config(materialized='view') }}\n")
    assert has_generated_header(text)
    assert "-- GENERATED by dvgen (render_stage); do not hand-edit." in text


@pytest.mark.parametrize("key", sorted(TEMPLATE_FILES))
def test_embedded_template_copies_match_template_project(key):
    rel, expected = TEMPLATE_FILES[key]
    path = TEMPLATE_RAW_VAULT / rel
    if not path.is_file():
        pytest.skip(f"Template_Project file not present: {path}")
    assert _body(path.read_text(encoding="utf-8")) == expected


def test_hub_stage_matches_template():
    art = _stage("stage_hub", "stg2_hub_cp_partners__party",
                 target="HUB_PARTY", source_model="stg_partner__cp_partners",
                 table="CP_PARTNERS",
                 record_source="!OPUS_PARTNER_CP_PARTNERS",
                 load_datetime="inc_job_updated_at", parent_code="HUB_PARTY",
                 parent_bk="part_id", header_notes=["Key: map.KEY PART_ID."])
    text = render_stage(art)
    _check_shape(text)
    assert _body(text) == TEMPLATE_HUB
    assert ("-- HEALTH STANDARD-MODEL per-table stage() for HUB_PARTY, "
            "table 'CP_PARTNERS'.\n-- Key: map.KEY PART_ID.\n") in text
    assert render(art) == text  # deterministic, same through dispatch


