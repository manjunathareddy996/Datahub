def test_bridge_view():
    art = Artifact(kind="bridge", path="models/x/bridge_claim_note__claim.sql",
                   name="bridge_claim_note__claim", data={
                       "hub": "HUB_CLAIM", "table": "CLAIM_NOTE",
                       "source_model": "stg_health__claim_note",
                       "joins": [{"model": "stg_health__claim_header",
                                  "alias": "b1",
                                  "on": [{"left": "t.case_id",
                                          "right": "b1.case_id"}]}],
                       "columns": [{"column": "bridge_claim_id",
                                    "expr": "b1.claim_id"}],
                       "header_notes": ["Shared key HUB_CASE (case_id)."]})
    text = render_bridge(art)
    _check_shape(text)
    assert render(art) == text
    assert "many-to-many" in text
    assert text.endswith(
        "select\n    t.*,\n    b1.claim_id as bridge_claim_id\n"
        "from {{ ref('stg_health__claim_note') }} as t\n"
        "inner join {{ ref('stg_health__claim_header') }} as b1\n"
        "    on t.case_id = b1.case_id\n")
    assert "-- Shared key HUB_CASE (case_id).\n" in text


def test_bridge_refuses_reused_alias():
    art = Artifact(kind="bridge", path="models/x/bridge_a__claim.sql",
                   name="bridge_a__claim", data={
                       "hub": "HUB_CLAIM", "table": "A",
                       "source_model": "stg_health__a",
                       "joins": [{"model": "stg_health__b", "alias": "t",
                                  "on": [{"left": "t.k", "right": "t.k"}]}],
                       "columns": [{"column": "claim_id", "expr": "t.claim_id"}]})
    with pytest.raises(RenderError):
        render_bridge(art)
