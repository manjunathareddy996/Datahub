def test_multi_active_branch_literal_childkey_and_coalesce():
    art = _stage("stage_sat",
                 "stg2_sat_bjaz_hm_gpa_bill_dtls__claim_benefit_head__room_rent",
                 target="SAT_CLAIM_BENEFIT_HEAD",
                 source_model="stg_health__bjaz_hm_gpa_bill_dtls",
                 table="BJAZ_HM_GPA_BILL_DTLS",
                 record_source="!OPUS_BJAZ_HM_GPA_BILL_DTLS",
                 load_datetime="inc_job_updated_at", parent_code="HUB_CLAIM",
                 parent_bk="claim_id",
                 childkey=[{"column": "BENEFITHEADCODE", "literal": "Room Rent"}],
                 payload=[{"column": "BENEFITAMOUNT",
                           "expr": ["room_rent_amt", "room_amt", "rent_amt"]}],
                 header_notes=["Coalesce: room_rent_amt (SETTLED#1), room_amt "
                               "(SETTLED#2), rent_amt (SETTLED#3)."])
    text = render_stage(art)
    _check_shape(text)
    assert ("hashed_columns:\n  CLAIM_HKEY: 'PARENT_NK'\n  HASHDIFF:\n"
            "    is_hashdiff: true\n    columns:\n      - 'BENEFITAMOUNT'\n"
            "      - 'BENEFITHEADCODE'\nderived_columns:\n"
            "  PARENT_BK: 'claim_id'\n"
            "  PARENT_NK: \"'HUB_CLAIM|' || (claim_id)\"\n"
            "  BENEFITHEADCODE: '!Room Rent'\n"
            "  BENEFITAMOUNT: 'coalesce(room_rent_amt, room_amt, rent_amt)'\n"
            "  LOAD_DATETIME: 'INC_JOB_UPDATED_AT'\n"
            "  RECORD_SOURCE: '!OPUS_BJAZ_HM_GPA_BILL_DTLS'\n") in text
    assert "-- Coalesce: room_rent_amt (SETTLED#1)" in text


