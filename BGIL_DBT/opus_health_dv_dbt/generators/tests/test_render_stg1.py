"""Unit tests for dvgen.render_stg1 (Requirements 3.2-3.8)."""
from __future__ import annotations

import pytest

from dvgen.emit import has_generated_header
from dvgen.model import Artifact
from dvgen.render_stg1 import (
    RenderStg1Error,
    column_alias,
    render_sources_yml,
    render_stg1,
)


def _col(name, kind="text", origin="index", is_key=False):
    return {"name": name, "kind": kind, "type_origin": origin, "is_key": is_key}


def _artifact(columns, evidence="catalogue_no", watermark="INC_JOB_UPDATED_AT",
              table="BA_CCP_INSURED_DETAILS", source="health_test_raw"):
    stem = table.lower()
    return Artifact(
        kind="stg1",
        path=f"models/staging/health/stg_health__{stem}.sql",
        name=f"stg_health__{stem}",
        data={"table": table, "stem": stem, "source": source,
              "columns": columns, "watermark": watermark,
              "watermark_evidence": evidence},
    )


DESIGN_COLUMNS = [
    _col("FIRST_NAME"),
    _col("DATE_OF_BIRTH", "timestamp"),
    _col("AGE", "number"),
    _col("CONTRACT_ID", "number", is_key=True),
    _col("NOTE", origin="untyped"),
]


def test_design_example_shape():
    text = render_stg1(_artifact(DESIGN_COLUMNS), project="OPUS")
    expected = (
        "-- GENERATED by dvgen (render_stg1); do not hand-edit.\n"
        "-- Staging model for source table BA_CCP_INSURED_DETAILS (Health LOB, OPUS).\n"
        "-- Casting: text -> nullif(trim(to_varchar(col)), ''); number -> ::number;\n"
        "--          date/timestamp -> ::timestamp_ntz. Key columns -> trimmed varchar.\n"
        "-- Types are Derived_Facts read from inputs/00_tables_index.DELTA3.json (4 cols)\n"
        "-- and legacy staging SQL (0 cols); 1 column untyped (cast as varchar).\n"
        "-- WATERMARK RISK: catalogue lists no INC_JOB_UPDATED_AT for this table.\n"
        "with source as (\n"
        "    select\n"
        "    \"AGE\"::number as age,\n"
        "    nullif(trim(to_varchar(\"CONTRACT_ID\")), '') as contract_id,\n"
        "    \"DATE_OF_BIRTH\"::timestamp_ntz as date_of_birth,\n"
        "    nullif(trim(to_varchar(\"FIRST_NAME\")), '') as first_name,\n"
        "    nullif(trim(to_varchar(\"NOTE\")), '') as note,\n"
        "    \"INC_JOB_UPDATED_AT\"::timestamp_ntz as inc_job_updated_at\n"
        "    from {{ source('health_test_raw', 'BA_CCP_INSURED_DETAILS') }}\n"
        ")\n"
        "select * from source\n"
    )
    assert text == expected
    assert has_generated_header(text)


def test_no_joins_hashing_or_derived_columns():
    text = render_stg1(_artifact(DESIGN_COLUMNS)).lower()
    for word in (" join ", "md5", "sha", "hash", "case when"):
        assert word not in text
    assert text.count("with source as (") == 1
    assert text.count("{{ source(") == 1


def test_no_risk_line_when_catalogue_has_watermark_or_unknown():
    for evidence in ("catalogue_yes", "unknown"):
        assert "WATERMARK RISK" not in render_stg1(
            _artifact(DESIGN_COLUMNS, evidence=evidence))


def test_watermark_in_columns_is_selected_once_and_last():
    cols = DESIGN_COLUMNS + [_col("INC_JOB_UPDATED_AT", "timestamp")]
    text = render_stg1(_artifact(cols, evidence="catalogue_yes"))
    assert text.count('"INC_JOB_UPDATED_AT"') == 1
    select_lines = [l for l in text.splitlines() if l.startswith("    ") and " as " in l]
    assert select_lines[-1].endswith("as inc_job_updated_at")
    assert "DELTA3.json (5 cols)" in text


def test_override_watermark_is_used():
    text = render_stg1(_artifact([_col("A")], watermark="REC_REFRESH_AT",
                                 evidence="unknown"))
    assert text.splitlines()[-4] == (
        '    "REC_REFRESH_AT"::timestamp_ntz as rec_refresh_at')


def test_key_column_is_trimmed_varchar_whatever_its_type():
    text = render_stg1(_artifact([_col("TS_KEY", "timestamp", is_key=True)]))
    assert "nullif(trim(to_varchar(\"TS_KEY\")), '') as ts_key" in text


def test_reserved_and_non_plain_aliases_are_quoted():
    assert column_alias("FROM") == '"FROM"'
    assert column_alias("subject") == '"SUBJECT"'
    assert column_alias("BODY") == '"BODY"'
    assert column_alias("2D_ECHO") == '"2D_ECHO"'
    assert column_alias("CLAIM_ID") == "claim_id"
    text = render_stg1(_artifact([_col("FROM"), _col("2D_ECHO", "number")]))
    assert "nullif(trim(to_varchar(\"FROM\")), '') as \"FROM\"" in text
    assert '"2D_ECHO"::number as "2D_ECHO"' in text


def test_legacy_counts_and_plain_mapping_input():
    cols = [_col("A", origin="legacy"), _col("B", "number", origin="legacy")]
    data = dict(_artifact(cols, evidence="unknown").data)
    text = render_stg1(data, legacy_label="legacy_v3 staging SQL")
    assert "(0 cols)\n-- and legacy_v3 staging SQL (2 cols); 0 columns untyped" in text


def test_deterministic_and_order_independent():
    a = render_stg1(_artifact(DESIGN_COLUMNS))
    b = render_stg1(_artifact(list(reversed(DESIGN_COLUMNS))))
    assert a == b
    assert a.endswith("\n") and not a.endswith("\n\n") and "\r" not in a


def test_bad_inputs_raise():
    with pytest.raises(RenderStg1Error):
        render_stg1(_artifact([_col("A"), _col("a")]))
    with pytest.raises(RenderStg1Error):
        render_stg1(_artifact([_col("A")], source="bad name"))
    with pytest.raises(RenderStg1Error):
        render_stg1(Artifact(kind="hub", path="models/x.sql", name="x",
                             data=_artifact([_col("A")]).data))


def test_sources_yml_opus():
    text = render_sources_yml(
        {"health_test_raw": ("health_test_raw_database", "health_test_raw_schema"),
         "health_raw": ("health_raw_database", "health_raw_schema")},
        ["bjaz_b", "BA_A", "BA_A"])
    expected = (
        "# GENERATED by dvgen (render_stg1); do not hand-edit.\n"
        "version: 2\n"
        "\n"
        "sources:\n"
        "  - name: health_raw\n"
        "    database: \"{{ var('health_raw_database') }}\"\n"
        "    schema: \"{{ var('health_raw_schema') }}\"\n"
        "    tables:\n"
        "      - name: BA_A\n"
        "      - name: BJAZ_B\n"
        "\n"
        "  - name: health_test_raw\n"
        "    database: \"{{ var('health_test_raw_database') }}\"\n"
        "    schema: \"{{ var('health_test_raw_schema') }}\"\n"
        "    tables:\n"
        "      - name: BA_A\n"
        "      - name: BJAZ_B\n"
    )
    assert text == expected
    assert has_generated_header(text)


def test_sources_yml_maximus_single_source():
    text = render_sources_yml(
        {"maximus_health_raw": ("maximus_health_raw_database",
                                "maximus_health_raw_schema")},
        ["MAXI_HLTH_X"])
    assert text.count("\n  - name: ") == 1
    assert "var('maximus_health_raw_schema')" in text


def test_sources_yml_rejects_bad_input():
    with pytest.raises(RenderStg1Error):
        render_sources_yml({}, ["A"])
    with pytest.raises(RenderStg1Error):
        render_sources_yml({"s": ("db",)}, ["A"])
    with pytest.raises(RenderStg1Error):
        render_sources_yml({"s": ("db", "sc")}, [])
