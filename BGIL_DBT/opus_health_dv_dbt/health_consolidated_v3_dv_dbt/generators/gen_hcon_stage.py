# -*- coding: utf-8 -*-
"""ONE WIDE STAGE PER VIEW. health_consolidated.

The stage view carries every staged column through unchanged and adds one BUSINESS-KEY column per
key slot declared on that view. It does NOT hash: hashing happens exactly once, downstream, in the
hub feed / link feed / satellite, so a business key has one spelling and one hash site.

Key expressions are emitted VERBATIM from their source -- separators and the inner coalesce of a
content hash are NOT tidied. A tidied key is a different key.

Reads build_artifacts/hcon_spec.json. Never the map.
"""
import collections
import json
import os
import sys

import hcon_names as N
from hcon_writeguard import PROJECT_ROOT, guarded_open, guarded_makedirs

SPEC_PATH = os.path.join(PROJECT_ROOT, "build_artifacts", "hcon_spec.json")
OUT_DIR = os.path.join(PROJECT_ROOT, "models", "stage")


def header(view, slots):
    byorigin = collections.Counter(s["origin"] for s in slots)
    lines = [
        "/* GENERATED by gen_hcon_stage.py -- models are generated, never hand-edited.",
        "   source view : %s   (run: %s)" % (view["table"], view["run"]),
        "   key slots on this view: %d   %s" % (len(slots), dict(byorigin) or "{}"),
        "   Key expressions are emitted VERBATIM from their source. Separators and the inner",
        "   coalesce of a content hash are NOT tidied; a tidied key is a different key.",
        "   This view does NOT hash. Hashing happens exactly once, downstream, so one business",
        "   key has one spelling and one hash site.",
    ]
    if any(s["origin"] == "legacy_emitted_sql" for s in slots):
        lines += [
            "   LEGACY KEY PROVENANCE (builder decision BD2): the legacy half of the settled map",
            "   carries ZERO resolved_key, so the slots marked legacy_emitted_sql were RECOVERED",
            "   from health_dv_dbt's emitted SQL, read-only. They are what legacy's generator",
            "   EMITTED, not what any map declares, and they cannot be validated against the",
            "   bundle. Legacy's loaded HASH VALUES are not reproduced -- only the business-key",
            "   EXPRESSION is carried over and re-hashed in this build's canonical explicit form.",
        ]
    if any(s["uses_normalise"] for s in slots):
        lines += [
            "   normalise() APPEARS BELOW and is UNDEFINED in both originals and in this project.",
            "   It is carried over verbatim inside a v2 content-hash expression and is introduced",
            "   into no new expression. UNRESOLVED -- see open item normalise-udf.",
        ]
    for s in slots:
        if s["degenerate_value"] is not None:
            lines.append("   degenerate sentinel on %s: %r -- rows reaching it are DIVERTED to "
                         "the reject log, never silently dropped."
                         % (s["bk_column"], s["degenerate_value"]))
    lines.append("*/")
    return "\n".join(lines)


def render(view, slots):
    out = ["{{ config(materialized='view') }}", header(view, slots), "",
           "with src as (",
           "    select * from {{ ref('%s') }}" % view["staging_model"],
           ")", "", "select", "    src.*"]
    for s in sorted(slots, key=lambda x: (x["vault_table"], x["bk_column"])):
        N.assert_identifier(s["bk_column"], "stage bk column")
        if s["semantics"] == "link":
            # a link key's legs are staged ONE COLUMN PER LEG, keyed by hub NAME, so the link feed
            # hashes legs rather than re-parsing an LNK(...) string
            for hub, leg in sorted((s["legs"] or {}).items()):
                if not leg or not leg.strip():
                    raise AssertionError("EMPTY LINK LEG for %s on %s" % (hub, view["table"]))
                col = N.bk_column(hub, s["source_columns"])
                out.append("    , %s as %s" % (leg.strip(), col))
        else:
            out.append("    , %s as %s" % (s["expression"], s["bk_column"]))
    out.append("from src")
    return "\n".join(out) + "\n"


def main():
    with open(SPEC_PATH, encoding="utf-8") as fh:
        spec = json.load(fh)
    guarded_makedirs(OUT_DIR)
    slots_by_view = collections.defaultdict(list)
    for s in spec["key_slots"]:
        slots_by_view[s["view"]].append(s)
    built = skipped = keyless = 0
    for view in spec["views"]:
        if not view["needs_cast"]:
            print("  SKIP %-34s no layer-1 cast exists for it, so there is nothing to stage"
                  % view["table"])
            skipped += 1
            continue
        slots = slots_by_view.get(view["table"], [])
        if not slots:
            keyless += 1
        path = os.path.join(OUT_DIR, view["stage_model"] + ".sql")
        with guarded_open(path) as fh:
            fh.write(render(view, slots))
        built += 1
    print("[stage] wide stages: %d models written, %d views skipped WITH A REASON" %
          (built, skipped))
    print("[stage] %d staged views carry NO key slot -- their payload can still be read but no "
          "row of theirs can reach a hub; every affected satellite feeder is in the unresolved "
          "register with the reason" % keyless)
    print("[stage] key slots staged: %d  (unit = one business-key column on one view)"
          % len(spec["key_slots"]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
