# -*- coding: utf-8 -*-
"""LOAD-TIME ASSERTIONS -- the registry hazard is a DATA question, so it gets a DATA test.

WHY THIS LAYER EXISTS
---------------------
Everything else in this build is static. The two questions that matter most here are not.

  A. CROSS-RUN COLLISION. The declared source precedence can only FIRE where a business-key VALUE
     collides across the two runs' DISJOINT registries. Whether that ever happens is UNANSWERABLE
     STATICALLY -- and it is exactly the unestablished thing. A hub-level business-key-column
     overlap cannot see it at any threshold: HUB_PARTY's overlap of three is IMD_CODE, PART_ID and
     RM_CODE, all intermediary-side, while on the member/customer population the overlap is ZERO.

  B. INTRA-RUN ARBITRARINESS. Within ONE run, several source views write one attribute, the map
     declares no precedence among them, and max() picks arbitrarily. NO CROSS-RUN REMEDY TOUCHES
     THIS -- the 95 legacy writers of SAT_PARTY_IDENTITY.'Party Full Name' are all the SAME run.

THE PREDICATE FOR B IS NARROW, AND DELIBERATELY SO
--------------------------------------------------
Only writers that NOTHING separates are arbitrary. TWO fields legitimately separate them:
`instance` and `redundant_of`. On SAT_PARTY_IDENTITY.'Party Full Name' (legacy): 95 writers, 75
separated by a resolved instance, 0 redundant_of, 20 genuinely undiscriminated over 20 tables.
Asserting over all 95 would report 75 CORRECT rows as defects on a new check's first run, and a
gate that over-accuses gets switched off and then protects nothing (s1.12). So B reads ONLY the
undiscriminated writers, straight from their stage views.

NOTHING HERE HAS BEEN EXECUTED. dbt is out of scope for this build, so every file below is EMITTED
AND UNRUN. A zero from an unrun assertion is not a zero; it is an absence of measurement, and each
file says so in its own header.
"""
import collections
import json
import os
import sys

import hcon_names as N
from hcon_writeguard import PROJECT_ROOT, guarded_open, guarded_makedirs

SPEC_PATH = os.path.join(PROJECT_ROOT, "build_artifacts", "hcon_spec.json")
OUT_DIR = os.path.join(PROJECT_ROOT, "models", "assertions")

UNRUN = [
    "   THIS ASSERTION HAS NOT BEEN EXECUTED. dbt is out of scope for this build, so this file is",
    "   EMITTED AND UNRUN. A zero from an unrun assertion is NOT a zero -- it is an absence of",
    "   measurement. Until it runs, the question below is OPEN, not answered.",
]


def render_cross_run(obj, hk, attrs):
    hdr = ["/* GENERATED by gen_hcon_assertions.py -- models are generated, never hand-edited."]
    hdr += UNRUN
    hdr += [
        "",
        "   WHAT THIS WOULD PROVE",
        "   ---------------------",
        "   The declared source precedence (v2 > legacy) can only FIRE where a business-key VALUE",
        "   collides across the two runs' DISJOINT registries. This counts the hash keys that",
        "   actually receive feed rows from BOTH runs.",
        "",
        "     0  => NO value collided across the two runs' registries. The precedence NEVER FIRED,",
        "           no legacy value was ever discarded, and the registry risk on this object --",
        "           still unreconciled in principle -- did not materialise in this data. THIS IS",
        "           THE ONLY SELF-SUFFICIENT ANSWER.",
        "     >0 => two registries produced THE SAME VALUE on the listed keys. READ THIS",
        "           CAREFULLY: that proves the VALUES collided, NOT that they denote the same",
        "           ENTITY. A shared CUST_ID / CUSTOMER_ID value may be one person, or two people",
        "           with coincidentally equal identifiers in different registries. SO A NON-ZERO",
        "           COUNT ESCALATES; IT DOES NOT RESOLVE. Treating it as proof of a merge would",
        "           assert the very thing that is undetermined.",
        "",
        "   object      : %s" % obj,
        "   hash key    : %s" % hk,
        "   cross-run-written attributes downstream of it (unit = one (satellite, attribute) pair;",
        "   writer counts are ALL writers, with the undiscriminated subset in brackets):",
    ]
    for s, a, nl, nv, ul, uv in attrs:
        hdr.append("     %-40s %-30s legacy %3d [%3d undisc] / v2 %3d [%3d undisc]"
                   % (s, a, nl, ul, nv, uv))
    hdr += [
        "",
        "   A DECLARED CONFLICT IS RECOVERABLE; A WRONG MERGE IS NOT, AFTER LOAD. That asymmetry",
        "   is why the cross-run position is declared and counted rather than resolved here.",
        "*/",
        "",
        "{{ config(materialized='view', tags=['assertion', 'unrun', 'cross_run_collision']) }}",
        "",
        "select",
        "    %s," % hk,
        "    count(distinct SOURCE_RUN) as RUNS_WRITING_THIS_KEY,",
        "    min(SOURCE_RUN) as FIRST_RUN,",
        "    max(SOURCE_RUN) as LAST_RUN,",
        "    count(*) as FEED_ROWS",
        "from {{ ref('%s') }}" % obj.lower(),
        "group by %s" % hk,
        "having count(distinct SOURCE_RUN) > 1",
    ]
    return "\n".join(hdr) + "\n"


def render_intra_run(sat, anchor, hk, groups, track="ratified"):
    """groups: list of (attribute, column, run, [(view, source_column, bk_column), ...])"""
    hdr = ["/* GENERATED by gen_hcon_assertions.py -- models are generated, never hand-edited."]
    hdr += UNRUN
    hdr += [
        "",
        "   WHAT THIS WOULD PROVE",
        "   ---------------------",
        "   THE LARGER NON-DETERMINISM, and the one NO cross-run decision reaches. WITHIN ONE RUN",
        "   several source views write the same attribute, the map declares NO precedence among",
        "   them, and max() picks ARBITRARILY. Refusing a subordinate RUN cannot touch this: the",
        "   writers below are all the SAME run.",
        "",
        "   It counts, per (hash key, attribute, run), how many DISTINCT values the UNDISCRIMINATED",
        "   writers of that one run supply.",
        "",
        "     0 rows => every undiscriminated same-run writer agreed on every key. max() was",
        "               arbitrary in FORM only and nothing was lost.",
        "     >0     => on each row listed, two or more views of the SAME run supplied DIFFERENT",
        "               values for one attribute of one key, and max() silently kept one. THOSE",
        "               ARE THE VALUES THIS BUILD PICKED ARBITRARILY.",
        "",
        "   THE PREDICATE IS NARROW ON PURPOSE. Only writers that NOTHING separates are arbitrary.",
        "   Writers carrying a resolved `instance` or a declared `redundant_of` are EXCLUDED: a",
        "   nominee's name and a policyholder's name on one satellite are DIFFERENT ROWS, not",
        "   competing writers. Asserting over all writers would report correct rows as defects --",
        "   on SAT_PARTY_IDENTITY.'Party Full Name' that would be 75 of 95.",
        "",
        "   WHY NO EXISTING GATE SEES THIS: check_collapse groups on",
        "   (table, satellite, attribute, instance, child_key), so it can only flag writers from",
        "   the SAME table. The groups below are CROSS-table, so they produce ZERO violations",
        "   there. A collapse figure from that gate bounds the same-table subset only.",
        "",
        "   satellite   : %s" % sat,
        "   track       : %s" % track,
        "   anchor      : %s" % anchor,
        "   hash key    : %s" % hk,
        "   groups asserted (unit = one (attribute, run) group of UNDISCRIMINATED writers):",
    ]
    for attr, col, run, ws in groups:
        hdr.append("     %-38s %-24s %d undiscriminated writer(s) over %d table(s)"
                   % (col, run, len(ws), len({v for v, _c, _b in ws})))
    hdr += [
        "",
        "   DECLARED, NOT RESOLVED: choosing among same-run writers would invent an authority the",
        "   map does not provide. The remedy is an intra-run precedence from the mapper or a",
        "   source ruling, and neither is available to this build. The mapping counterparty has",
        "   taken the cross-table groups.",
        "*/",
        "",
        "{{ config(materialized='view', tags=['assertion', 'unrun', 'intra_run_arbitrary']) }}",
        "",
        "with undiscriminated as (",
    ]
    branches = []
    for attr, col, run, ws in groups:
        for view, srccol, bk in ws:
            branches.append(
                "    select\n"
                "        %s as %s,\n"
                "        %s as ATTRIBUTE_NAME,\n"
                "        %s as SOURCE_RUN,\n"
                "        %s as SOURCE_VIEW,\n"
                "        cast(%s as varchar) as ATTRIBUTE_VALUE\n"
                "    from {{ ref('%s') }}\n"
                "    where %s is not null"
                % (N.hash_expr(anchor, bk), hk, N.sql_literal(col), N.sql_literal(run),
                   N.sql_literal(view), srccol, N.stage_model(view), bk))
    hdr.append("\n    union all\n".join(branches))
    hdr += [
        ")",
        "",
        "select",
        "    %s," % hk,
        "    ATTRIBUTE_NAME,",
        "    SOURCE_RUN,",
        "    count(distinct ATTRIBUTE_VALUE) as DISTINCT_VALUES_FROM_ONE_RUN,",
        "    count(distinct SOURCE_VIEW) as SOURCE_VIEWS_DISAGREEING",
        "from undiscriminated",
        "where ATTRIBUTE_VALUE is not null",
        "group by %s, ATTRIBUTE_NAME, SOURCE_RUN" % hk,
        "having count(distinct ATTRIBUTE_VALUE) > 1",
    ]
    return "\n".join(hdr) + "\n"


def render_index(cross, intra, carved, census):
    lines = [
        "/* GENERATED by gen_hcon_assertions.py.",
        "   The two open questions this build cannot answer statically, as one list.",
    ]
    lines += UNRUN
    lines += [
        "",
        "   A. CROSS-RUN COLLISION -- %d assertion(s) over the %d shared object(s) written by BOTH"
        % (len(cross), len(carved)),
        "      runs. 0 means the declared precedence never fired. >0 proves the VALUES collided,",
        "      NOT that they denote the same ENTITY, so >0 ESCALATES rather than resolves.",
        "   B. INTRA-RUN ARBITRARINESS -- %d assertion(s), over UNDISCRIMINATED writers only."
        % len(intra),
        "      THIS IS THE LARGER NON-DETERMINISM and NO decision taken so far addresses it.",
        "      Single-active surface: %d group(s) / %d column(s), of which CROSS-table %d/%d and"
        % (census["single_active"]["groups"], census["single_active"]["columns"],
           census["single_active"]["cross_table_groups"],
           census["single_active"]["cross_table_columns"]),
        "      SAME-table %d/%d. check_collapse can only see the SAME-table subset."
        % (census["single_active"]["same_table_groups"],
           census["single_active"]["same_table_columns"]),
        "",
        "   FIRST CASE TO READ, named by the mapping counterparty:",
        "   SAT_PARTY_IDENTITY.'Party Full Name' -- 95 legacy writers, 75 separated by a resolved",
        "   instance, 0 redundant_of, 20 genuinely undiscriminated over 20 distinct tables.",
        "*/",
        "",
        "{{ config(materialized='view', tags=['assertion', 'unrun', 'index']) }}",
        "",
    ]
    rows = ["    select %s as ASSERTION_MODEL, %s as ASSERTION_CLASS, %s as SUBJECT, "
            "'NEVER_EXECUTED' as EXECUTION_STATE"
            % (N.sql_literal(n), N.sql_literal(k), N.sql_literal(s))
            for n, k, s in sorted(cross + intra)]
    lines.append("\n    union all\n".join(rows) if rows else
                 "    select cast(null as varchar) as ASSERTION_MODEL,\n"
                 "           cast(null as varchar) as ASSERTION_CLASS,\n"
                 "           cast(null as varchar) as SUBJECT,\n"
                 "           'NEVER_EXECUTED' as EXECUTION_STATE\n"
                 "    where false")
    return "\n".join(lines) + "\n"


def main():
    with open(SPEC_PATH, encoding="utf-8") as fh:
        spec = json.load(fh)
    guarded_makedirs(OUT_DIR)
    import gen_hcon_vault as V
    carved = V.cross_run_shared_objects(spec)
    census = spec["meta"]["intra_run_fanin_census"]

    emitted = set()
    for d in ("vault/satellites", "vault/refs", "augmented"):
        p = os.path.join(PROJECT_ROOT, "models", *d.split("/"))
        if os.path.isdir(p):
            emitted |= {f[:-4] for f in os.listdir(p) if f.endswith(".sql")}

    # ---------------- A. cross-run collision
    by_obj = collections.defaultdict(list)
    for S in spec["satellites"]:
        anchor = S["anchor"] or ""
        if anchor not in carved or S["code"].lower() not in emitted:
            continue
        for p in S["payload"]:
            fr = p.get("fanin_by_run") or {}
            if len(fr) < 2:
                continue
            L = fr.get("opus_health_legacy_v4", {})
            Vv = fr.get("opus_health_v2", {})
            by_obj[anchor].append((S["code"], p["attribute"],
                                   L.get("all_writers", 0), Vv.get("all_writers", 0),
                                   L.get("undiscriminated", 0), Vv.get("undiscriminated", 0)))
    cross = []
    for obj in sorted(by_obj):
        name = N.budget("assert_cross_run_collision__" + obj.lower())
        with guarded_open(os.path.join(OUT_DIR, name + ".sql")) as fh:
            fh.write(render_cross_run(obj, N.hash_key(obj), sorted(by_obj[obj])))
        cross.append((name, "cross_run_collision", obj))

    # ---------------- B. intra-run arbitrariness, UNDISCRIMINATED writers only
    intra = []
    for S in spec["satellites"]:
        anchor = S["anchor"]
        if not anchor or S["code"].lower() not in emitted:
            continue
        bk = {(f["view"], f["run"]): f["key_slot_bk_column"]
              for f in S["feeders"] if f["emitted"] and f["key_slot_bk_column"]}
        groups = []
        for p in S["payload"]:
            for run, fr in sorted((p.get("fanin_by_run") or {}).items()):
                if fr["undiscriminated"] < 2:
                    continue
                ws = [(w["view"], w["source_column"], bk.get((w["view"], run)))
                      for w in p["writers"]
                      if w["run"] == run and not w.get("discriminated")]
                ws = [(v, c, b) for v, c, b in ws if b]
                if len({v for v, _c, _b in ws}) < 2 and len(ws) < 2:
                    continue
                if len(ws) < 2:
                    continue
                groups.append((p["attribute"], p["column"], run, sorted(ws)))
        if not groups:
            continue
        # The TRACK is part of the identity. Without it a satellite with both a ratified and an
        # unratified build unit renders ONE filename twice and the second write destroys the
        # first -- which lost ten assertions, including the largest on the build.
        name = N.budget("assert_intra_run_arbitrary__" + S["code"].lower()
                        + ("" if S["track"] == "ratified" else "__" + S["track"]))
        with guarded_open(os.path.join(OUT_DIR, name + ".sql")) as fh:
            fh.write(render_intra_run(S["code"], anchor, N.hash_key(anchor), groups,
                                      S["track"]))
        intra.append((name, "intra_run_arbitrary", "%s [%s]" % (S["code"], S["track"])))

    # EVERY EMITTED MODEL NAME MUST BE UNIQUE. Two models on one filename is the defect class
    # that has now bitten this build three times, and it is invisible downstream: the file exists,
    # its refs resolve, and only a count that disagrees with a directory listing reveals it.
    allnames = [n for n, _k, _s in cross + intra]
    dup = sorted({n for n in allnames if allnames.count(n) > 1})
    if dup:
        raise AssertionError(
            "ASSERTION MODEL NAME COLLISION -- %d name(s) emitted more than once: %s. One write "
            "would destroy the other and the loss would be invisible." % (len(dup), dup))
    with guarded_open(os.path.join(OUT_DIR, "assertion_index.sql")) as fh:
        fh.write(render_index(cross, intra, carved, census))
    on_disk = sorted(f[:-4] for f in os.listdir(OUT_DIR) if f.endswith(".sql"))
    want = sorted(allnames + ["assertion_index"])
    if on_disk != want:
        raise AssertionError(
            "ASSERTION WRITE COUNT MISMATCH: intended %d model(s), %d on disk. Missing %s; "
            "unexpected %s. A write that silently replaced another is exactly what this asserts."
            % (len(want), len(on_disk), sorted(set(want) - set(on_disk)),
               sorted(set(on_disk) - set(want))))

    sa = census["single_active"]
    print("[assertions] A: %d cross-run collision assertion(s) over %d shared object(s) written "
          "by BOTH runs, covering %d (satellite, attribute) pair(s). UNIT = one emitted .sql."
          % (len(cross), len(carved), sum(len(v) for v in by_obj.values())))
    print("[assertions]    >0 proves the VALUES collided, NOT that they denote the same ENTITY: "
          ">0 ESCALATES, and 0 is the only self-sufficient answer.")
    print("[assertions] B: %d intra-run arbitrariness assertion(s), predicate restricted to "
          "UNDISCRIMINATED writers (no instance AND no redundant_of)." % len(intra))
    print("[assertions]    Had the predicate counted ALL writers it would have reported 75 of 95 "
          "correct rows as defects on SAT_PARTY_IDENTITY.'Party Full Name' alone.")
    print("[assertions] intra-run surface, single-active (unit = group of undiscriminated "
          "writers): %d group(s) / %d column(s); CROSS-table %d/%d, SAME-table %d/%d"
          % (sa["groups"], sa["columns"], sa["cross_table_groups"], sa["cross_table_columns"],
             sa["same_table_groups"], sa["same_table_columns"]))
    print("[assertions]    check_collapse groups on (table, satellite, attribute, instance, "
          "child_key) and can therefore only see the SAME-table subset; the cross-table "
          "population is the larger one and was invisible to that gate on both sides.")
    print("[assertions] %d model(s) intended, %d on disk -- ASSERTED EQUAL, and every name "
          "asserted unique. Ten intra-run assertions were silently overwriting each other before "
          "the track joined the name." % (len(want), len(on_disk)))
    print("[assertions] NOTHING HAS BEEN EXECUTED -- dbt is out of scope, so a zero here would be "
          "an absence of measurement, not a clean result.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
