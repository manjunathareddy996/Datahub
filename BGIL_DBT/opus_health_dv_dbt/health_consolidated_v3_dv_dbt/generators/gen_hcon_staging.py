# -*- coding: utf-8 -*-
"""LAYER 1 -- casts for mapped views. health_consolidated.

A view gets a cast because it NEEDS one, not because it is in the map (BUILD_RULES.md s6.1). A view
whose every column is unconsumed -- no key slot reads it and no satellite payload reads it -- gets
no model, and the omission is PRINTED with its reason so it can never be mistaken for a source gap.

Reads build_artifacts/hcon_spec.json. Never the map.
"""
import json
import os
import sys

import hcon_names as N
from hcon_writeguard import PROJECT_ROOT, guarded_open, guarded_makedirs

SPEC_PATH = os.path.join(PROJECT_ROOT, "build_artifacts", "hcon_spec.json")
OUT_DIR = os.path.join(PROJECT_ROOT, "models", "staging")

# BUILDER DECISION BD3: the pinned bundle contains NO datatype catalogue, so every column is cast
# to varchar. Inventing a type from a column name is a fabricated datum. Supply a catalogue here to
# overrule.
def TYPE_FOR_COLUMN(view, column):
    return "varchar"


def header(view):
    return (
        "/* GENERATED by gen_hcon_staging.py -- models are generated, never hand-edited.\n"
        "   source view  : %s\n"
        "   source run   : %s\n"
        "   convention   : UPPER_SNAKE_PHYSICAL (RATIFIED; counted from BOTH originals' emitted\n"
        "                  satellite SQL, never read from a description)\n"
        "   columns      : %d in the map, %d CONSUMED downstream\n"
        "   datatypes    : every column cast to varchar. The pinned bundle carries NO datatype\n"
        "                  catalogue, and a type inferred from a column name is a fabricated\n"
        "                  datum (builder decision BD3).\n"
        "*/" % (view["table"], view["run"], view["column_count"], view["consumed_count"]))


def render(view):
    lines = ["{{ config(materialized='view') }}", header(view), "", "select"]
    body = []
    for col in view["columns"]:
        N.assert_identifier(col, "staging column of %s" % view["table"])
        body.append("    cast(%s as %s) as %s"
                    % (col, TYPE_FOR_COLUMN(view["table"], col), col))
    lines.append(",\n".join(body))
    lines.append("from {{ source('%s', '%s') }}" % (view["source_name"], view["table"]))
    return "\n".join(lines) + "\n"


def main():
    with open(SPEC_PATH, encoding="utf-8") as fh:
        spec = json.load(fh)
    guarded_makedirs(OUT_DIR)                       # s6.4: the writer creates its own directory
    built = skipped = 0
    for view in spec["views"]:
        if not view["needs_cast"]:
            print("  SKIP %-34s no column of this view is consumed by any key slot or satellite "
                  "payload, so no cast is needed (s6.1)" % view["table"])
            skipped += 1
            continue
        path = os.path.join(OUT_DIR, view["staging_model"] + ".sql")
        with guarded_open(path) as fh:
            fh.write(render(view))
        built += 1
    print("[staging] layer-1 casts: %d models written, %d views skipped WITH A REASON" %
          (built, skipped))
    print("[staging] unit = one source view; population = the 115 views of the settled map")
    return 0


if __name__ == "__main__":
    sys.exit(main())
