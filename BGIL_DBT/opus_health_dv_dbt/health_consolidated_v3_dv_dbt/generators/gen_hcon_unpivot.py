# -*- coding: utf-8 -*-
"""ONE ROW PER INSTANCE -- for COLUMN-AS-INSTANCE FAMILIES ONLY. health_consolidated.

A column-as-instance family is a repeating group spread ACROSS COLUMNS: the discriminator lives in
the COLUMN NAME, not in any column value, so a wide row has to fan out to one row per populated
instance before a satellite can key on it.

SCOPE, AND WHY IT IS NARROW
---------------------------
This layer fires ONLY where the map marks the family. The marker is the bracketed token
childkey[column_as_instance] inside key_derivation. key_derivation is PROSE and is in
hcon_keyrules.PROSE_DENY: not one character of it is rendered. It is read ONLY as an exact
bracketed token, because it is the sole signal for this family in this bundle, and the alternative
is to guess the layer's population from column names -- which is how a fabricated discriminator
gets built.

THE INSTANCE LABEL IS READ, NEVER INFERRED FROM A COLUMN PREFIX. P_ and M_ on
BJAZ_BANDHAN_MEDI_CLAM mean PERMANENT and MAILING, not proposer/member; the prefix reads naturally
as the wrong one, and inferring it would overwrite a member's mailing address with their permanent
one. The settled map already carries the right answer in target.instance.

NOT IN SCOPE: the BJAZ_WS_FAMILY_DTLS_BANDHAN MEMBER1..8 + SELF group. It LOOKS like a
column-as-instance family and the map does NOT mark it as one, because its discriminator --
'Member Sequence' -- has no value anywhere. Synthesising the ordinal from the column name is
exactly the fabricated datum this build refuses: MEMBER1..8 makes it look trivially derivable and
SELF has no number, so any derivation invents a value for one slot in nine. Declared in
build_artifacts/reports/declared_unresolved_grain_hcon.json, not built.

Reads build_artifacts/hcon_spec.json. Never the map.
"""
import json
import os
import sys

import hcon_names as N
from hcon_writeguard import PROJECT_ROOT, guarded_open, guarded_makedirs

SPEC_PATH = os.path.join(PROJECT_ROOT, "build_artifacts", "hcon_spec.json")
OUT_DIR = os.path.join(PROJECT_ROOT, "models", "unpivot")


def render(fam, view, slot_bk):
    sat = fam["satellite"]
    inst_col = "INSTANCE_LABEL"
    lines = ["{{ config(materialized='view') }}",
             "/* GENERATED by gen_hcon_unpivot.py -- models are generated.",
             "   BESPOKE LAYER (BUILD_RULES.md s6.5): column-as-instance fan-out.",
             "   source view   : %s   (run: %s)" % (fam["view"], fam["run"]),
             "   satellite     : %s" % sat,
             "   discriminator : taken from the COLUMN's declared target.instance, never from any",
             "                   column value and NEVER inferred from a column prefix -- P_ and M_",
             "                   mean PERMANENT and MAILING on this estate, not proposer/member.",
             "   fan-out       : 1 parent row -> up to %d instance rows" % len(fam["instances"]),
             "   Each branch below is one source column carrying one literal instance. A branch",
             "   emits nothing where its column is null, so the fan-out is the POPULATED width of",
             "   the repeating group rather than a fixed %d." % len(fam["instances"]),
             "   marker read: childkey[%s] in key_derivation, as an exact bracketed token only."
             % fam["marker"],
             "*/", ""]
    branches = []
    for inst in fam["instances"]:
        cols = fam["branches"][inst]
        for c in cols:
            N.assert_identifier(c["source_column"], "unpivot source column")
            branches.append(
                "    select\n"
                "        %s as %s,\n"
                "        %s as %s,\n"
                "        %s as INSTANCE_ATTRIBUTE,\n"
                "        %s as INSTANCE_VALUE,\n"
                "        '%s' as INSTANCE_SOURCE_COLUMN,\n"
                "        '%s' as RECORD_SOURCE,\n"
                "        '%s' as SOURCE_RUN\n"
                "    from {{ ref('%s') }}\n"
                "    where %s is not null"
                % (slot_bk, slot_bk, N.sql_literal(inst), inst_col,
                   N.sql_literal(c["attribute"]), c["source_column"],
                   c["source_column"], fam["view"], fam["run"],
                   N.stage_model(fam["view"]), c["source_column"]))
    lines.append("\nunion all\n".join(branches))
    return "\n".join(lines) + "\n"


def main():
    with open(SPEC_PATH, encoding="utf-8") as fh:
        spec = json.load(fh)
    guarded_makedirs(OUT_DIR)
    bk_for = {}
    for S in spec["satellites"]:
        for f in S["feeders"]:
            if f["emitted"]:
                bk_for[(S["code"], f["view"], f["run"])] = f["key_slot_bk_column"]
    built = 0
    skipped = []
    for fam in spec["unpivot"]:
        bk = bk_for.get((fam["satellite"], fam["view"], fam["run"]))
        if not bk:
            skipped.append((fam, "no anchor key slot on %s, so a fanned-out row has no hub key "
                                 "to attach to" % fam["view"]))
            continue
        name = N.unpivot_model(fam["view"], fam["satellite"], fam["instances"][0])
        with guarded_open(os.path.join(OUT_DIR, name + ".sql")) as fh:
            fh.write(render(fam, fam["view"], bk))
        built += 1
    print("[unpivot] column-as-instance fan-outs: %d models written" % built)
    for fam, why in skipped:
        print("  NOT BUILT %-30s %-36s %s" % (fam["satellite"], fam["view"], why))
    print("[unpivot] families declared by the map marker childkey[column_as_instance]: %d; "
          "built %d; refused %d" % (len(spec["unpivot"]), built, len(skipped)))
    print("[unpivot] unit = one (satellite, view, run) family; MATCHER = the exact bracketed "
          "token childkey[column_as_instance] in key_derivation, with at least two distinct "
          "block-level instance labels on the same feeder")
    print("[unpivot] NOT IN SCOPE and NOT BUILT: the BJAZ_WS_FAMILY_DTLS_BANDHAN MEMBER1..8+SELF "
          "group. Its discriminator 'Member Sequence' has NO value anywhere and synthesising the "
          "ordinal from the column name would invent a value for one slot in nine (SELF has no "
          "number). Declared, never built.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
