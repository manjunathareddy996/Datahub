# -*- coding: utf-8 -*-
"""THE REJECT LOG -- every key a feed refused, in one place. health_consolidated.

A hub feed's WHERE clause IS its declared reject predicate. A row failing it does not reach the
hub, and without this layer that loss is invisible: the hub simply has fewer rows and nothing says
why. Every reject class declared in the map gets a per-slot reject model, and one table unions them.

FOUR reject classes are declared in this bundle, and they were SWEPT FROM THE FIELD rather than
read from the profile -- the profile shows them only inside truncated samples, from which three are
visible. The fourth (content_hash_composite_guarded, 33 declarations) was found because the sweep
assertion fired.

Reads build_artifacts/hcon_spec.json. Never the map.
"""
import collections
import json
import os
import sys

import hcon_keyrules as K
import hcon_names as N
from hcon_writeguard import PROJECT_ROOT, guarded_open, guarded_makedirs

SPEC_PATH = os.path.join(PROJECT_ROOT, "build_artifacts", "hcon_spec.json")
OUT_DIR = os.path.join(PROJECT_ROOT, "models", "reject_log")

COLS = ("SOURCE_VIEW", "SOURCE_RUN", "TARGET_TABLE", "REJECT_CLASS", "REJECT_SLOT",
        "KEY_OPERANDS", "DEGENERATE_VALUE", "SILENT_DROP")


def render_reject(slot, decl):
    cls = decl["class"]
    # SILENT_DROP names the classes where Snowflake would drop the row with no error at all. A
    # null-annihilating composite is the sharpest: one blank operand nulls the whole key.
    silent = cls in ("composite_null_annihilating",)
    lines = ["{{ config(materialized='view') }}",
             "/* GENERATED by gen_hcon_rejectlog.py -- models are generated.",
             "   source view  : %s   (run: %s)" % (slot["view"], slot["run"]),
             "   target       : %s" % slot["vault_table"],
             "   reject class : %s" % cls,
             "   reject slot  : %s" % decl["slot"],
             "   operands     : %s" % ", ".join(str(o) for o in decl["operands"]),
             "   This is the COMPLEMENT of the hub feed's WHERE clause. A row here is a row that",
             "   did NOT reach a hub, link or satellite. Counted, never absorbed."]
    if silent:
        lines += ["   SILENT DROP: this class nulls the whole key when ONE operand is blank, so on",
                  "   Snowflake the row vanishes with no error. That is why the loss is counted."]
    if decl.get("reclassified_from"):
        lines.append("   reclassified from: %s" % decl["reclassified_from"])
    lines.append("*/")
    dv = decl.get("degenerate_value") if decl.get("degenerate_value") is not None \
        else slot["degenerate_value"]
    lines += ["", "select",
              "    '%s' as SOURCE_VIEW," % slot["view"],
              "    '%s' as SOURCE_RUN," % slot["run"],
              "    '%s' as TARGET_TABLE," % slot["vault_table"],
              "    %s as REJECT_CLASS," % N.sql_literal(cls),
              "    %s as REJECT_SLOT," % N.sql_literal(str(decl["slot"])),
              "    %s as KEY_OPERANDS," % N.sql_literal(", ".join(str(o)
                                                                  for o in decl["operands"])),
              "    %s as DEGENERATE_VALUE," % (N.sql_literal(str(dv)) if dv is not None
                                               else "cast(null as varchar)"),
              "    %s as SILENT_DROP" % ("true" if silent else "false"),
              "from {{ ref('%s') }}" % N.stage_model(slot["view"]),
              "where (%s) is null" % slot["expression"]]
    if dv is not None:
        lines[-1] = lines[-1] + "\n   or (%s) = %s" % (slot["bk_column"],
                                                       N.sql_literal(str(dv)))
    return "\n".join(lines) + "\n"


def main():
    with open(SPEC_PATH, encoding="utf-8") as fh:
        spec = json.load(fh)
    guarded_makedirs(OUT_DIR)
    models, classes = [], collections.Counter()
    for slot in spec["key_slots"]:
        decls = slot.get("reject_declarations") or []
        if not decls and slot["reject_class"]:
            decls = [{"class": slot["reject_class"], "slot": "expression",
                      "operands": slot["source_columns"],
                      "degenerate_value": slot["degenerate_value"]}]
        for i, d in enumerate(decls):
            if d["class"] not in K.REJECT_CLASSES:
                raise AssertionError("UNRECOGNISED reject class %r reached the reject log"
                                     % d["class"])
            name = N.reject_model(slot["vault_table"].lower(), slot["view"],
                                  slot["id"] + "#%d" % i)
            with guarded_open(os.path.join(OUT_DIR, name + ".sql")) as fh:
                fh.write(render_reject(slot, d))
            models.append(name)
            classes[d["class"]] += 1

    if models:
        parts = ["select %s from {{ ref('%s') }}" % (", ".join(COLS), m) for m in sorted(models)]
        body = ["{{ config(materialized='table') }}",
                "/* GENERATED by gen_hcon_rejectlog.py.",
                "   Every rejected key in one place, across %d reject model(s) over %d key slot(s)."
                % (len(models), len(spec["key_slots"])),
                "   A row here is a row that did NOT reach a hub, link or satellite.",
                "   Reject classes present: %s" % dict(classes),
                "*/", "", "\nunion all\n".join(parts)]
        with guarded_open(os.path.join(OUT_DIR, "reject_log.sql")) as fh:
            fh.write("\n".join(body) + "\n")
        summary = ["{{ config(materialized='table') }}",
                   "/* GENERATED by gen_hcon_rejectlog.py.",
                   "   One row per (view, target, class): how many keys each predicate refused.",
                   "   A ZERO here is a measurement; a MISSING row is a slot with no declared",
                   "   reject predicate, which is a different thing and must not read as clean.",
                   "*/", "",
                   "select SOURCE_VIEW, SOURCE_RUN, TARGET_TABLE, REJECT_CLASS, SILENT_DROP,",
                   "       count(*) as REJECTED_ROWS",
                   "from {{ ref('reject_log') }}",
                   "group by SOURCE_VIEW, SOURCE_RUN, TARGET_TABLE, REJECT_CLASS, SILENT_DROP"]
        with guarded_open(os.path.join(OUT_DIR, "reject_log_summary.sql")) as fh:
            fh.write("\n".join(summary) + "\n")

    slots_without = [s["id"] for s in spec["key_slots"]
                     if not (s.get("reject_declarations") or s["reject_class"])]
    print("[rejectlog] %d per-slot reject models + reject_log + reject_log_summary" % len(models))
    print("[rejectlog] reject classes emitted (unit = one declaration): %s" % dict(classes))
    print("[rejectlog] key slots with NO declared reject predicate: %d of %d. Their losses are "
          "NOT counted anywhere, which is a GAP, not a zero -- the legacy-recovered slots carry "
          "no declaration because legacy's emitted SQL declares none."
          % (len(slots_without), len(spec["key_slots"])))
    return 0


if __name__ == "__main__":
    sys.exit(main())
