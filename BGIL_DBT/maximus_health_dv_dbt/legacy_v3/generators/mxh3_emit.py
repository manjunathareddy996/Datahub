"""Shared emit helpers: the spec reader, SQL headers, and the progress checkpoint.

Every generator reads build_artifacts/mxh3_spec.json -- never the map.
"""
import json
import os

import mxh3_keyrules as K
import mxh3_names as N
import mxh3_writeguard as W

SPEC_PATH = os.path.join(W.ARTIFACTS, "mxh3_spec.json")
PROGRESS = os.path.join(W.ARTIFACTS, "reports", "stage1_progress.json")
MODELS = W.MODELS

SOURCE_NAME = "maxi_hlth_v3"

ENGINE_NOTE = (
    "ENGINE ASSUMPTION: Snowflake. A key that renders NULL is DROPPED by the load, so a\n"
    "   blank row would become unlogged data loss that reads as a sparse source. Every such\n"
    "   row is therefore diverted to the reject log by the EXACT boolean complement of the\n"
    "   emit predicate below. An absent EAV label materialises as '' and not NULL, so every\n"
    "   operand is written nullif(trim(<operand>),''). The SAME rule applies either way.")


def spec():
    if not os.path.isfile(SPEC_PATH):
        raise AssertionError(
            "mxh3_spec.json is absent. Run build_mxh3_spec.py first: every generator reads "
            "the SPEC, never the map.")
    with open(SPEC_PATH, encoding="utf-8") as fh:
        return json.load(fh)


def header(generator, lines):
    """Emit the header as '--' LINE comments, not a /* */ block.

    The shared gate's strip_sql_comments removes only '--' comments, so a /* */
    header carrying English apostrophes leaves an odd quote count and the gate
    reports an unbalanced string literal on every model.
    """
    out = ["-- GENERATED by %s -- models are generated, never hand-edited." % generator]
    for ln in lines:
        # A note may be a single multi-line string; every physical line needs the
        # comment marker or the remainder becomes bare SQL.
        for phys in str(ln).split("\n"):
            out.append(("--   " + phys).rstrip())
    return "\n".join(out)


def config(materialized="view", extra=None):
    bits = ["materialized='%s'" % materialized]
    if extra:
        bits += extra
    return "{{ config(%s) }}" % ", ".join(bits)


def write_model(subdir, name, sql, generator):
    """Write one model. The directory is created by the generator that writes it (s6.4)."""
    d = os.path.join(MODELS, *subdir.split("/"))
    W.ensure_dir(d)
    K.assert_no_prose_in_sql(sql, "%s/%s.sql" % (subdir, name))
    return W.write(os.path.join(d, name + ".sql"), sql, generator=generator)


def checkpoint(layer, count, detail=None):
    """Record progress after each layer so an interruption costs one layer, not the run."""
    W.ensure_dir(os.path.dirname(PROGRESS))
    data = {"layers": []}
    if os.path.isfile(PROGRESS):
        try:
            with open(PROGRESS, encoding="utf-8") as fh:
                data = json.load(fh)
        except ValueError:
            data = {"layers": []}
    data["layers"] = [x for x in data.get("layers", []) if x.get("layer") != layer]
    data["layers"].append({"layer": layer, "models": count, "detail": detail})
    data["models_so_far"] = sum(x["models"] for x in data["layers"])
    W.write(PROGRESS, json.dumps(data, indent=1), generator="mxh3_emit.py")
    print("  [checkpoint] %-28s %4d model(s)   running total %d"
          % (layer, count, data["models_so_far"]))
    return data


def reset_progress():
    if os.path.isfile(PROGRESS):
        os.remove(PROGRESS)


def cast(view, col):
    """cast(<col> as <declared type>) as <col>, from the source index's own types."""
    t = (K.column_type(view, col) or "varchar").lower()
    if t in ("number", "integer", "int", "float", "decimal", "numeric"):
        t = "number"
    elif t in ("date", "timestamp", "datetime"):
        t = t
    else:
        t = "varchar"
    # X::type, never cast(X as type): the gate's alias regex reads a trailing
    # `as varchar)` as a column alias, which it is not.
    return "%s::%s as %s" % (N.quote_ident(col), t, N.quote_ident(col))


