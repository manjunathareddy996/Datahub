# -*- coding: utf-8 -*-
"""gen_mtv2_exemptions.py -- the sanctioned coverage exemptions, GENERATED.

BUILD_RULES 8.2: a mapped column that reaches no satellite payload is either a defect or a
recorded decision, and the ONLY channel that tells a reader which is
`vault_tools/accepted_uncovered.txt`. Before this generator existed, this project had ZERO lines
there and 17 uncovered columns, so every one of them read exactly like the silent drop check 6
was written to catch -- even though the build had a reason for each in its spec.

The reasons are DERIVED from `build_artifacts/mtv2_spec.json` `census.coverage`, never typed. A
reason typed into a shared file goes stale the next build and nothing would notice.

This generator does NOT write into vault_tools. vault_tools is shared by every project in this
workspace, and a per-project generator editing it would be one LOB's build changing another's
gate. It writes `build_artifacts/accepted_uncovered.mtv2.txt`, which is the exact text
`vault_tools/accepted_uncovered.txt` must carry for this project; `selfcheck_mtv2.py` then
ASSERTS the two agree, so drift is a failing check rather than a silent divergence.

Directives implemented here: D-COVERAGE-EXEMPTIONS-ARE-GENERATED.
"""
import json
import os
import sys

import mtv2_names as N
import build_mtv2_spec as S

try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
except Exception:
    pass

OUT = os.path.join(N.ARTIFACTS, "accepted_uncovered.mtv2.txt")
PROJECT_KEY = os.path.basename(N.PROJECT)

HEADER = [
    "# --- %s, stage 1. GENERATED by generators/gen_mtv2_exemptions.py from" % PROJECT_KEY,
    "# --- build_artifacts/mtv2_spec.json census.coverage. Do not edit by hand: the build",
    "# --- asserts that vault_tools/accepted_uncovered.txt carries exactly these lines for this",
    "# --- project, so a hand edit fails the build rather than going stale quietly.",
    "#",
    "# Every line here is also a finding in build_artifacts/reports/stage1_report.json, routed",
    "# to whoever can answer it. An exemption RECORDS a gap; it does not close one.",
]


def one_line(text):
    """A reason is one line. A newline in a reason would split one exemption into two lines, the
    second of which parses as a different project's entry."""
    return " ".join(str(text).split())


def lines_for(spec):
    out = list(HEADER)
    for u in spec["census"]["coverage"]["uncovered"]:
        out.append("%s %s.%s   # %s [%s; routed %s]"
                   % (PROJECT_KEY, u["satellite"], u["column"], one_line(u["reason"]),
                      u["class"], u["routing"]))
    return out


def main():
    spec = json.load(open(S.SPEC_PATH, encoding="utf-8"))
    body = "\n".join(lines_for(spec)) + "\n"
    N.ensure_dir(N.ARTIFACTS)
    N.assert_writable(OUT)
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(body)
    cov = spec["census"]["coverage"]
    print("gen_mtv2_exemptions -> %s" % OUT)
    print("  coverage             : %d of %d mapped column(s) reach a payload"
          % (cov["covered"], cov["total"]))
    print("  exemption line(s)    : %d   %s" % (len(cov["uncovered"]), cov["by_class"]))
    print("  MERGE TARGET         : vault_tools/accepted_uncovered.txt (shared; this generator")
    print("                         does not write it -- selfcheck_mtv2.py asserts it matches)")


if __name__ == "__main__":
    main()
