-- FEED for SAT_PARTY_IDENTIFICATION from stg2_mt__clm_clmd_clmrsk_rska_msp_msd_prop_pv.
-- One satfeed per stage (no UNION) so the sat's per-source watermark and change detection stay intact.
--
-- Payload columns are renamed to the shared names the partner projects write (AADHAARNUMBER, ...).
-- RECORD_SOURCE gets the instance (IDENTIFICATION_TYPE_CODE) appended. sat_multi_source builds the
-- object columns keyed by RECORD_SOURCE (group prefix removed), so without this suffix several ID
-- instances of one stage would share a key and only one would survive.
-- The unpivot / stg2 models are untouched, so hub_party keeps its original RECORD_SOURCE.

select
    PARTY_HKEY__CLAIMANT as PARTY_HKEY,
    HASHDIFF_PARTY_IDENTIFICATION as HASHDIFF,
    AADHAAR_NUMBER as AADHAAR_NUMBER,
    AADHAAR_VERIFICATION_STATUS as AADHAAR_VERIFICATION_STATUS,
    AGE_PROOF_TYPE as AGE_PROOF_TYPE,
    CIN_NUMBER as CIN_NUMBER,
    CKYC_NUMBER as CKYCNUMBER,
    DRIVING_LICENCE_EXPIRY_DATE as DRIVING_LICENCE_EXPIRY_DATE,
    DRIVING_LICENCE_NUMBER as DRIVING_LICENCE_NUMBER,
    EIA_NUMBER as EIA_NUMBER,
    GSTIN,
    GST_REGISTRATION_STATUS as GST_REGISTRATION_STATUS,
    GST_TAXPAYER_TYPE as GST_TAXPAYER_TYPE,
    IDENTIFICATION_EXPIRY_DATE as IDENTIFICATION_EXPIRY_DATE,
    IDENTIFICATION_ISSUE_DATE as IDENTIFICATION_ISSUE_DATE,
    IDENTIFICATION_ISSUING_AUTHORITY as IDENTIFICATION_ISSUING_AUTHORITY,
    IDENTIFICATION_NUMBER as IDENTIFICATION_NUMBER,
    IDENTIFICATION_VERIFIED_INDICATOR as IDENTIFICATION_VERIFIED_INDICATOR,
    INSURANCE_REPOSITORY_NAME as INSURANCEREPOSITORYNAME,
    NREGA_CARD_NUMBER as NREGA_CARD_NUMBER,
    OVD_CATEGORY as OVD_CATEGORY,
    PAN_NUMBER as PAN_NUMBER,
    PAN_VERIFICATION_STATUS as PAN_VERIFICATION_STATUS,
    PASSPORT_EXPIRY_DATE as PASSPORTEXPIRYDATE,
    PASSPORT_NUMBER as PASSPORT_NUMBER,
    TAN_NUMBER as TAN_NUMBER,
    VOTER_ID_NUMBER as VOTER_ID_NUMBER,
    LOAD_DATETIME,
    RECORD_SOURCE || '_' || IDENTIFICATION_TYPE_CODE as RECORD_SOURCE
from {{ ref('stg2_mt__clm_clmd_clmrsk_rska_msp_msd_prop_pv') }}
where PARTY_HKEY__CLAIMANT is not null
