        POLICY_HKEY as POLICY_HKEY,
        ENDORSEMENT_NUMBER as ENDORSEMENT_NUMBER,
        EFFECTIVE_DATE as EFFECTIVE_DATE,
        ENDORSEMENT_REASON as ENDORSEMENT_REASON,
        ENDORSEMENT_TYPE as ENDORSEMENT_TYPE,
