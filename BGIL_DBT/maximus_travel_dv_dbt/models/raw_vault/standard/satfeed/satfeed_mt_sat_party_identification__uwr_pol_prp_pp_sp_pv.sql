-- FEED for SAT_PARTY_IDENTIFICATION from stg2_mt_up__uwr_pol_prp_pp_sp_pv__sat_party_identification.
-- One satfeed per stage (no UNION) so the sat's per-source watermark and change detection stay intact.
--
-- Payload columns are renamed to the shared names the partner projects write (AADHAARNUMBER, ...).
-- RECORD_SOURCE gets the instance (IDENTIFICATION_TYPE_CODE) appended. sat_multi_source builds the
-- object columns keyed by RECORD_SOURCE (group prefix removed), so without this suffix several ID
-- instances of one stage would share a key and only one would survive.
-- The unpivot / stg2 models are untouched, so hub_party keeps its original RECORD_SOURCE.

select
    PARTY_HKEY__PROPOSER as PARTY_HKEY,
    HASHDIFF_PARTY_IDENTIFICATION as HASHDIFF,
    AADHAAR_NUMBER as AADHAARNUMBER,
    AADHAAR_VERIFICATION_STATUS as AADHAARVERIFICATIONSTATUS,
    AGE_PROOF_TYPE as AGEPROOFTYPE,
    CIN_NUMBER as CINNUMBER,
    CKYC_NUMBER as CKYCNUMBER,
    DRIVING_LICENCE_EXPIRY_DATE as DRIVINGLICENCEEXPIRYDATE,
    DRIVING_LICENCE_NUMBER as DRIVINGLICENCENUMBER,
    EIA_NUMBER as EIANUMBER,
    GSTIN,
    GST_REGISTRATION_STATUS as GSTREGISTRATIONSTATUS,
    GST_TAXPAYER_TYPE as GSTTAXPAYERTYPE,
    IDENTIFICATION_EXPIRY_DATE as IDENTIFICATIONEXPIRYDATE,
    IDENTIFICATION_ISSUE_DATE as IDENTIFICATIONISSUEDATE,
    IDENTIFICATION_ISSUING_AUTHORITY as IDENTIFICATIONISSUINGAUTHORITY,
    IDENTIFICATION_NUMBER as IDENTIFICATIONNUMBER,
    IDENTIFICATION_VERIFIED_INDICATOR as IDENTIFICATIONVERIFIEDINDICATOR,
    INSURANCE_REPOSITORY_NAME as INSURANCEREPOSITORYNAME,
    NREGA_CARD_NUMBER as NREGACARDNUMBER,
    OVD_CATEGORY as OVDCATEGORY,
    PAN_NUMBER as PANNUMBER,
    PAN_VERIFICATION_STATUS as PANVERIFICATIONSTATUS,
    PASSPORT_EXPIRY_DATE as PASSPORTEXPIRYDATE,
    PASSPORT_NUMBER as PASSPORTNUMBER,
    TAN_NUMBER as TANNUMBER,
    VOTER_ID_NUMBER as VOTERIDNUMBER,
    LOAD_DATETIME,
    RECORD_SOURCE || '_' || IDENTIFICATION_TYPE_CODE as RECORD_SOURCE
from {{ ref('stg2_mt_up__uwr_pol_prp_pp_sp_pv__sat_party_identification') }}
where PARTY_HKEY__PROPOSER is not null
